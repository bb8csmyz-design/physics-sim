import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      'つりあいの位置',
      p(
        'ばね定数 $k$ のばねに質量 $m$ のおもりをつるすと、ばねが $d$ だけ伸びたところで弾性力と重力がつりあう。',
      ),
      eq('kd = mg \\quad\\Longrightarrow\\quad d = \\frac{mg}{k}'),
    ),
    section(
      '復元力と単振動',
      p(
        'つりあいの位置を原点とし、鉛直上向きを正とする $x$ 軸をとる。おもりが $x$ の位置にあるとき、ばねの伸びは $d - x$ なので、おもりにはたらく合力は',
      ),
      eq('F = k(d - x) - mg = -kx'),
      p(
        '重力の分がつりあいの伸び $d$ で打ち消され、合力は水平ばねと同じ形の復元力になる。したがっておもりは、つりあいの位置を中心とする単振動をする。',
      ),
      eq(
        'a = -\\omega^2 x, \\qquad \\omega = \\sqrt{\\frac{k}{m}}, \\qquad T = 2\\pi\\sqrt{\\frac{m}{k}}',
      ),
      p(
        '周期に $g$ は含まれない。質量を変えるとつりあいの位置（$d$）も周期も変わるが、$g$ が変わってもつりあいの位置がずれるだけで周期は変わらない。',
      ),
    ),
    section(
      'エネルギー保存',
      p(
        '弾性力と重力はどちらも保存力なので、運動エネルギー・弾性エネルギー・重力の位置エネルギーの和が一定に保たれる。',
      ),
      eq('\\frac{1}{2}mv^2 + \\frac{1}{2}k(d - x)^2 + mgx = \\text{一定}'),
      p('$kd = mg$ を使って整理すると、'),
      eq('\\frac{1}{2}k(d - x)^2 + mgx = \\frac{1}{2}kx^2 + \\frac{1}{2}kd^2'),
      p(
        'なので、つりあいの位置を基準にとれば $\\frac{1}{2}mv^2 + \\frac{1}{2}kx^2 = \\frac{1}{2}kA^2$（水平ばねと同じ形）になる。エネルギーのグラフで、弾性エネルギーと重力の位置エネルギーがそれぞれ変化しても、和 $E$ が一定であることを確かめよう。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '鉛直ばねでも「つりあいの位置を中心とした単振動」。まずつりあいの伸び $d = mg/k$ を求め、振動の中心を決める',
        '振幅は「振動の中心から端まで」。自然長の位置から測らない',
        '弾性エネルギーは「自然長からの伸び」で、$\\frac{1}{2}kx^2$ は「つりあいの位置からの変位」で書く。どちらの基準で考えているかを混同しない',
        'ばねが自然長より縮む（$x > d$）こともある。その間、弾性力は下向き',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$m = 0.50$ kg, $k = 20$ N/m のとき、つりあいの伸びと周期は？',
        p(
          '$d = 0.50 \\times 9.8 / 20 = 0.245$ m、$T = 2\\pi\\sqrt{0.50/20} \\approx 0.99$ s。「この条件での値」で確かめよう。',
        ),
      ),
      question(
        'つりあいの位置から 0.15 m 引き下げて静かに放した。最高点でばねは伸びているか、縮んでいるか（$m = 0.50$ kg, $k = 20$ N/m）。',
        p(
          '最高点はつりあいの位置の 0.15 m 上。$d = 0.245$ m より小さいので、まだ 0.095 m 伸びている。初期変位を $-0.30$ m にすると最高点で縮むことを確かめよう。',
        ),
      ),
      question(
        'ばねを切らずに、この装置を月面（重力加速度が約 1/6）に持っていくと、周期はどうなるか。',
        p(
          '変わらない（$T = 2\\pi\\sqrt{m/k}$ に $g$ は含まれない）。つりあいの伸び $d$ は 1/6 になる。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '運動方程式 $ma = k(d - x) - mg$ を、刻み幅 $\\Delta t = 1$ ms の速度ベルレ法（シンプレクティック積分法）で解いている。解析解・周期の公式との一致と、重力の位置エネルギーを含めた力学的エネルギーの保存を自動テストで確認している。',
      ),
    ),
  );
}
