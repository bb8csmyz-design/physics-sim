import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '運動量保存則',
      p(
        '物体 A, B が衝突するとき、A が B から受ける力と B が A から受ける力は、作用・反作用の法則により大きさが等しく逆向き。したがって A と B が受ける力積も大きさが等しく逆向きで、2 物体の運動量の和は変わらない。',
      ),
      eq("m_A v_A + m_B v_B = m_A v_A' + m_B v_B'"),
      p(
        '床がなめらかで水平方向に外力がはたらかないので、衝突の前後を通じて運動量の和は一定。「運動量」のグラフで、$p_A$ と $p_B$ が衝突で変化しても、和が一定であることを確かめよう。',
      ),
    ),
    section(
      '反発係数（はねかえり係数）',
      p('衝突後に離れる速さと衝突前に近づく速さの比を反発係数 $e$ という。'),
      eq("e = -\\frac{v_B' - v_A'}{v_B - v_A} \\qquad (0 \\le e \\le 1)"),
      ul(
        '$e = 1$: 弾性衝突（運動エネルギーが保存される）',
        '$0 < e < 1$: 非弾性衝突',
        '$e = 0$: 完全非弾性衝突（衝突後に一体となって動く）',
      ),
      p('運動量保存則と反発係数の式を連立すると、衝突後の速度が求まる。'),
      eq(
        "v_A' = \\frac{m_A v_A + m_B v_B - e\\,m_B(v_A - v_B)}{m_A + m_B}, \\qquad v_B' = \\frac{m_A v_A + m_B v_B + e\\,m_A(v_A - v_B)}{m_A + m_B}",
      ),
    ),
    section(
      '失われる運動エネルギー',
      p(
        '$e < 1$ の衝突では運動エネルギーの一部が熱や音、変形のエネルギーになって失われる。その大きさは',
      ),
      eq('\\Delta K = \\frac{1}{2}\\frac{m_A m_B}{m_A + m_B}(1 - e^2)(v_A - v_B)^2'),
      p(
        '運動量は保存されても、運動エネルギーは保存されるとは限らない。反発係数を変えて、「失われた運動エネルギー」がどう変わるかを確かめよう。',
      ),
    ),
    section(
      '重心の運動',
      p('外力がはたらかないとき、重心は衝突の前後を通じて一定の速度で動く。'),
      eq('v_G = \\frac{m_A v_A + m_B v_B}{m_A + m_B}'),
      p('「重心 G」を表示して、衝突の瞬間にも重心の動きが変わらないことを確かめよう。'),
    ),
    note(
      '入試のポイント',
      ul(
        '衝突の問題は「運動量保存則」と「反発係数の式」の 2 本を連立する',
        '速度は向きを含めた値で書く（右向き正なら、左向きの速度は負）。反発係数の式の符号に注意',
        '同じ質量の弾性衝突では速度が入れかわる',
        '静止した壁との衝突では運動量は保存されない（壁が外力を及ぼす）。はね返りの速さは $e$ 倍',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$m_A = 1.0$ kg, $m_B = 2.0$ kg, $v_A = 3.0$ m/s, $v_B = -1.0$ m/s, $e = 0.80$ のとき、衝突後の速度は？',
        p(
          "運動量の和は $1.0 \\times 3.0 + 2.0 \\times (-1.0) = 1.0$ kg·m/s、近づく速さは $4.0$ m/s なので $v_A' = (1.0 - 0.80 \\times 2.0 \\times 4.0)/3.0 = -1.8$ m/s、$v_B' = (1.0 + 0.80 \\times 1.0 \\times 4.0)/3.0 = 1.4$ m/s。「この条件での値」で確かめよう。",
        ),
      ),
      question(
        '2 つの物体の質量を等しくし、$e = 1$ にすると何が起こるか。',
        p('速度が入れかわる。B を静止させておくと、A が止まり B が A の速度で動き出す。'),
      ),
      question(
        '$e = 0$ にしたとき、失われる運動エネルギーは最大になるか。',
        p('なる。$\\Delta K$ は $1 - e^2$ に比例し、$e = 0$ で最大。'),
      ),
    ),
    section(
      '数値計算について',
      p(
        '衝突していない間は等速直線運動なので解析解で進め、接触する瞬間はステップの途中でも厳密に求めている（刻み幅によらない）。衝突は瞬間的とし、運動量保存則と反発係数の式から衝突後の速度を決める。運動量の保存、反発係数の定義、運動エネルギーの損失の公式、重心の等速運動を自動テストで確認している。',
      ),
    ),
  );
}
