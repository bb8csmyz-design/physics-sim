import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '力の分解と運動方程式',
      p(
        '斜面に沿って上向きを正とする。重力 $mg$ を斜面に平行な成分 $mg\\sin\\theta$（斜面下向き）と垂直な成分 $mg\\cos\\theta$ に分ける。斜面に垂直な方向はつりあっているので、垂直抗力は $N = mg\\cos\\theta$。',
      ),
      p("滑っている物体には、運動と逆向きに大きさ $\\mu' N$ の動摩擦力がはたらく。"),
      eq(
        "\\begin{aligned} \\text{上昇中:}\\quad ma &= -mg\\sin\\theta - \\mu' mg\\cos\\theta \\\\ \\text{下降中:}\\quad ma &= -mg\\sin\\theta + \\mu' mg\\cos\\theta \\end{aligned}",
      ),
      p(
        'どちらも加速度が一定なので、区間ごとに等加速度直線運動になる。摩擦力の向きが変わるので、上りと下りで加速度の大きさが違う（上りのほうが大きい）。',
      ),
    ),
    section(
      '最高到達距離',
      p(
        "上昇中の加速度の大きさを $a_1 = g(\\sin\\theta + \\mu'\\cos\\theta)$ とすると、$v^2 - v_0^{\\,2} = -2a_1 L$ より",
      ),
      eq(
        "L = \\frac{v_0^{\\,2}}{2g(\\sin\\theta + \\mu'\\cos\\theta)}, \\qquad t_1 = \\frac{v_0}{g(\\sin\\theta + \\mu'\\cos\\theta)}",
      ),
    ),
    section(
      '静止摩擦力と摩擦角',
      p(
        '止まった物体には静止摩擦力がはたらき、重力の斜面成分とつりあう（大きさ $mg\\sin\\theta$）。静止摩擦力には上限（最大静止摩擦力 $\\mu N$）があるので、',
      ),
      eq('mg\\sin\\theta \\le \\mu mg\\cos\\theta \\iff \\tan\\theta \\le \\mu'),
      p(
        "なら止まったまま、$\\tan\\theta > \\mu$ なら滑り出す。$\\tan\\theta_0 = \\mu$ となる角 $\\theta_0$ を摩擦角という。滑り降りるときの加速度の大きさは $a_2 = g(\\sin\\theta - \\mu'\\cos\\theta)$ で、出発点を通過する速さは",
      ),
      eq(
        "v = \\sqrt{2a_2 L} = v_0\\sqrt{\\frac{\\sin\\theta - \\mu'\\cos\\theta}{\\sin\\theta + \\mu'\\cos\\theta}}",
      ),
      p(
        "「摩擦力 $f$」のグラフで、滑っている間は一定の大きさ $\\mu'N$、止まると静止摩擦力 $mg\\sin\\theta$ に切りかわることを確かめよう。",
      ),
    ),
    section(
      'エネルギーの収支',
      p(
        '動摩擦力は運動と逆向きにはたらくので、常に負の仕事をする。その大きさ（動摩擦力 × 滑った道のり）だけ力学的エネルギーが減り、熱 $Q$ になる。',
      ),
      eq("\\frac{1}{2}mv^2 + mgh + Q = \\text{一定}, \\qquad Q = \\mu' N \\times (\\text{道のり})"),
      p(
        '垂直抗力は運動の向きと垂直なので仕事をしない。エネルギーの棒グラフで $K + U + Q$ が一定であることを確かめよう。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '摩擦力の向きは「運動（滑る向き）と逆向き」。上りと下りで向きが変わるので、運動方程式を分けて立てる',
        '止まった後に滑り出すかどうかは $\\tan\\theta$ と静止摩擦係数 $\\mu$ の大小で判定する（動摩擦係数ではない）',
        '静止摩擦力の大きさは「つりあいから決まる」。$\\mu N$ は上限（最大静止摩擦力）であって、いつもこの値ではない',
        '摩擦熱は「摩擦力 × 道のり」。変位ではなく道のりを使う',
      ),
    ),
    section(
      '考えてみよう',
      question(
        "$\\theta = 30^\\circ$, $\\mu = 0.5$, $\\mu' = 0.3$, $v_0 = 5.0$ m/s で打ち出した。最高点で止まった後、物体は滑り降りるか。",
        p(
          '$\\tan 30^\\circ \\approx 0.58 > \\mu = 0.5$ なので滑り降りる。$\\mu$ を 0.6 にすると最高点で止まったままになることを確かめよう。',
        ),
      ),
      question(
        '上の条件で、最高到達距離 $L$ はいくらか。',
        p(
          '$a_1 = 9.8 \\times (0.50 + 0.3 \\times 0.866) \\approx 7.45$ m/s² より $L = 25/(2 \\times 7.45) \\approx 1.68$ m。「この条件での値」で確かめよう。',
        ),
      ),
      question(
        '質量を 2 倍にすると、最高到達距離はどうなるか。',
        p(
          '変わらない。重力も垂直抗力も摩擦力も $m$ に比例するので、加速度は $m$ によらない。発熱 $Q$ は 2 倍になる。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '各区間（上昇中・下降中・静止中）は等加速度運動なので、数値積分ではなく解析解で時間を進めている。速度が $0$ になる瞬間や斜面の端に達する瞬間でステップを区切るので、刻み幅によらず厳密な結果になる。公式との一致と、$K + U + Q$ が一定であることを自動テストで確認している。',
      ),
    ),
  );
}
