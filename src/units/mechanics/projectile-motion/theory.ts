import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '運動を水平と鉛直に分ける',
      p(
        '投射点の真下の地面を原点とし、水平右向きに $x$ 軸、鉛直上向きに $y$ 軸をとる。空気抵抗がなければ、物体にはたらく力は重力 $mg$（鉛直下向き）だけなので、',
      ),
      ul(
        '水平方向: 力がはたらかない → 速度 $v_0\\cos\\theta$ の等速直線運動',
        '鉛直方向: 加速度 $-g$ の等加速度直線運動（初速度 $v_0\\sin\\theta$）',
      ),
      eq(
        '\\begin{aligned} x &= v_0\\cos\\theta \\cdot t, & v_x &= v_0\\cos\\theta \\\\ y &= h + v_0\\sin\\theta \\cdot t - \\tfrac{1}{2}gt^2, & v_y &= v_0\\sin\\theta - gt \\end{aligned}',
      ),
      p(
        '$t$ を消去すると $y$ は $x$ の 2 次関数になり、軌道は放物線になる。「速度の成分」を表示して、$v_x$ が一定のまま $v_y$ だけが一様に減っていくことを確かめよう。',
      ),
    ),
    section(
      '最高点の高さと水平到達距離',
      p('最高点では $v_y = 0$ になる（速度は水平で、速さは $0$ ではない）。'),
      eq('t_1 = \\frac{v_0\\sin\\theta}{g}, \\qquad H = h + \\frac{v_0^{\\,2}\\sin^2\\theta}{2g}'),
      p('地面から投げた（$h = 0$）とき、滞空時間は $t_2 = 2t_1$ で、水平到達距離は'),
      eq(
        'R = v_0\\cos\\theta \\cdot \\frac{2v_0\\sin\\theta}{g} = \\frac{v_0^{\\,2}\\sin 2\\theta}{g}',
      ),
      p(
        '$R$ は $\\theta = 45^\\circ$ で最大になり、$\\theta$ と $90^\\circ - \\theta$ では同じ値になる。「この条件での値」で確かめよう。',
      ),
    ),
    section(
      '速さに比例する空気抵抗',
      p(
        '空気抵抗が速度と逆向きで大きさ $kv$ の力だとすると、運動方程式は成分ごとに次のようになる。',
      ),
      eq('m\\frac{dv_x}{dt} = -kv_x, \\qquad m\\frac{dv_y}{dt} = -mg - kv_y'),
      p('十分時間がたつと重力と抵抗力がつりあい、鉛直下向きに一定の速さ（終端速度）で落ちる。'),
      eq('mg = kv_{\\mathrm{T}} \\quad\\Longrightarrow\\quad v_{\\mathrm{T}} = \\frac{mg}{k}'),
      p(
        '抵抗力は物体の運動を常に妨げるので、最高点は低く、到達距離は短くなる。軌道は放物線ではなく、下りのほうが急な非対称な形になる。「空気抵抗なしの軌道」を重ねて比べよう。',
      ),
    ),
    section(
      'エネルギー',
      p('空気抵抗がなければ、重力だけが仕事をするので力学的エネルギーが保存される。'),
      eq('\\frac{1}{2}mv^2 + mgy = \\frac{1}{2}mv_0^{\\,2} + mgh = \\text{一定}'),
      p(
        'これから着地の速さ $\\sqrt{v_0^{\\,2} + 2gh}$ が投射角によらないことが分かる。空気抵抗があると力学的エネルギーは減り、その分が熱 $Q$ になる（$K + U + Q$ が一定）。エネルギーのグラフで確かめよう。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '「水平は等速・鉛直は等加速度」に分解し、両方に共通の時刻 $t$ でつなぐ',
        '最高点の条件は $v_y = 0$、着地の条件は $y = 0$。どちらの条件で $t$ を決めるかをはっきりさせる',
        '同じ高さに戻るまでの時間は最高点までの時間の 2 倍（空気抵抗がないときだけ成り立つ）',
        '終端速度は「力のつりあい」から求める（加速度 $0$）',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '地面から $v_0 = 15$ m/s で投げるとき、最も遠くまで届く角度とその距離は？',
        p(
          '$\\theta = 45^\\circ$ で $R = v_0^{\\,2}/g = 225/9.8 \\approx 23$ m。投射角のスライダーで、$30^\\circ$ と $60^\\circ$ で同じ距離になることも確かめよう。',
        ),
      ),
      question(
        '高さ 19.6 m の台から水平に（$\\theta = 0^\\circ$）投げた。着地までの時間は初速度によって変わるか。',
        p(
          '変わらない。鉛直方向は初速度 $0$ の自由落下なので $t = \\sqrt{2h/g} = 2.0$ s。初速度を変えても滞空時間が同じことを確かめよう。',
        ),
      ),
      question(
        '空気抵抗があるとき、最高点に達するまでの時間と、最高点から着地までの時間はどちらが長いか。',
        p(
          '下りのほうが長い。上りでは重力と抵抗力がどちらも下向きで速く減速するが、下りでは抵抗力が上向きで加速がにぶる。$k$ を大きくして $v_y$-$t$ グラフで確かめよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '空気抵抗は速度に依存する力なので、運動方程式を刻み幅 $\\Delta t = 1$ ms の 4 次ルンゲ＝クッタ法（RK4）で解いている。空気抵抗がないときは RK4 が放物線を厳密に再現する。抵抗による発熱 $Q = \\int kv^2\\,dt$ も同時に積分し、$K + U + Q$ が一定であること、解析解（空気抵抗ありの指数関数解を含む）と一致することを自動テストで確認している。',
      ),
    ),
  );
}
