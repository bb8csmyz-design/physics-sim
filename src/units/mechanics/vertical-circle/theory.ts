import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '中心方向の運動方程式と張力',
      p(
        '長さ $r$ の糸につけた質量 $m$ の小球が、最下点から角 $\\theta$ の位置を速さ $v$ で通過するとき、中心方向には糸の張力 $T$ と重力の成分 $mg\\cos\\theta$（中心と逆向き）がはたらく。円運動の中心方向の運動方程式は',
      ),
      eq(
        'm\\frac{v^2}{r} = T - mg\\cos\\theta \\quad\\Longrightarrow\\quad T = m\\left(\\frac{v^2}{r} + g\\cos\\theta\\right)',
      ),
      p(
        '速さが一定でない円運動でも、中心方向にはこの式が成り立つ。接線方向には重力の成分 $mg\\sin\\theta$ だけがはたらき、速さを変える。',
      ),
    ),
    section(
      'エネルギー保存と速さ',
      p(
        '張力は運動の向きと常に垂直なので仕事をしない。重力だけが仕事をするので、最下点からの高さを $h = r(1 - \\cos\\theta)$ として',
      ),
      eq('\\frac{1}{2}mv_0^{\\,2} = \\frac{1}{2}mv^2 + mgh'),
      p('これを張力の式に代入すると、張力は位置 $\\theta$ だけで書ける。'),
      eq('T = m\\left(\\frac{v_0^{\\,2}}{r} - 2g + 3g\\cos\\theta\\right)'),
      p(
        '$T$ は最下点で最大 $m(v_0^{\\,2}/r + g)$、最高点で最小になる。「張力 T」のグラフで確かめよう。',
      ),
    ),
    section(
      '1 周する条件と糸がたるむ条件',
      p(
        '糸は引くことしかできない（$T \\ge 0$）。最高点（$\\theta = \\pi$）で $T \\ge 0$ となる条件から',
      ),
      eq(
        'T_{\\text{最高点}} = m\\left(\\frac{v_0^{\\,2}}{r} - 5g\\right) \\ge 0 \\iff v_0 \\ge \\sqrt{5gr}',
      ),
      ul(
        '$v_0 \\ge \\sqrt{5gr}$: 糸がたるまずに 1 周する',
        '$v_0 \\le \\sqrt{2gr}$: 中心の高さまでしか上がらず、振り子のように往復する（$T > 0$ のまま）',
        '$\\sqrt{2gr} < v_0 < \\sqrt{5gr}$: 中心より上で $T = 0$ になって糸がたるみ、その後は放物運動をする',
      ),
      p('糸がたるむ位置は $T = 0$ から'),
      eq('\\cos\\theta^* = -\\frac{v_0^{\\,2} - 2gr}{3gr}'),
      p('「糸がたるむ点」を表示し、小球がその点で円から離れることを確かめよう。'),
    ),
    note(
      '入試のポイント',
      ul(
        '円運動の問題は「中心方向の運動方程式」と「エネルギー保存」の 2 本の式を連立する',
        '1 周する条件は「最高点で速さ $> 0$」ではなく「最高点で張力 $T \\ge 0$」。糸の場合は $v_0 \\ge \\sqrt{5gr}$',
        'レール（円筒）の内側を回る小球でも、垂直抗力 $N \\ge 0$ が条件になり同じ結果になる。棒につけた場合は最高点で速さ $\\ge 0$ でよい（$v_0 \\ge \\sqrt{4gr}$）',
        '糸がたるんだ後は放物運動。たるむ瞬間の速度は円の接線方向',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$r = 1.0$ m のとき、1 周させるのに必要な最下点での速さはいくらか。',
        p(
          '$\\sqrt{5gr} = \\sqrt{5 \\times 9.8 \\times 1.0} = 7.0$ m/s。$v_0 = 7.0$ m/s にして、最高点で張力がほぼ $0$ になることを確かめよう。',
        ),
      ),
      question(
        '$r = 1.0$ m, $v_0 = 6.0$ m/s のとき、糸がたるむのは最下点から何 m の高さか。',
        p(
          '$\\cos\\theta^* = -(36 - 19.6)/29.4 \\approx -0.558$ より $h = r(1 - \\cos\\theta^*) \\approx 1.56$ m。「この条件での値」で確かめよう。',
        ),
      ),
      question(
        '質量を 2 倍にすると、1 周するのに必要な速さはどうなるか。',
        p(
          '変わらない（$\\sqrt{5gr}$ は $m$ を含まない）。ただし張力は $m$ に比例して 2 倍になる。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '糸が張っている間は、接線方向の運動方程式 $r\\ddot{\\theta} = -g\\sin\\theta$ を刻み幅 $\\Delta t = 1$ ms の吉田の 4 次シンプレクティック法で解いている。張力が $0$ になる瞬間は二分法で求めて放物運動（解析解）に切りかえ、糸が再び張った時点で止める（糸が急に張ると撃力がはたらき、力学的エネルギーが保存されないため）。張力・1 周の条件・たるむ位置の公式との一致と、エネルギー保存を自動テストで確認している。',
      ),
    ),
  );
}
