import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '剛体のつりあいの条件',
      p(
        '大きさのある物体（剛体）が静止し続けるには、「並進運動を始めない」ための力のつりあいと、「回転を始めない」ための力のモーメントのつりあいの両方が必要である。',
      ),
      eq('\\sum \\vec{F} = \\vec{0}, \\qquad \\sum M = 0'),
      p(
        '力のモーメントは「力の大きさ × 回転の軸から作用線までの距離（うでの長さ）」。つりあっているときは、どの点のまわりで考えてもモーメントの和は $0$ になるので、未知の力が多く集まる点を軸に選ぶと計算が楽になる。',
      ),
    ),
    section(
      'はしごにはたらく力',
      p(
        '長さ $L$、質量 $m$ のはしごが、なめらかな壁と粗い床の間に角 $\\theta$ で立てかけてあり、下端から $d$ の位置に質量 $M$ の人がいる。はたらく力は、重力 $mg$（はしごの中点）と $Mg$、床の垂直抗力 $N_1$ と静止摩擦力 $f$（下端）、壁の垂直抗力 $N_2$（上端。壁はなめらかなので摩擦力はない）。',
      ),
      eq(
        '\\begin{aligned} \\text{水平:}\\quad & f = N_2 \\\\ \\text{鉛直:}\\quad & N_1 = (m + M)g \\\\ \\text{下端のまわり:}\\quad & N_2 L\\sin\\theta = mg\\frac{L}{2}\\cos\\theta + Mg\\,d\\cos\\theta \\end{aligned}',
      ),
      p('「モーメントのうで」を表示すると、それぞれの力の作用線までの距離が分かる。'),
    ),
    section(
      '滑り出す条件',
      p(
        'はしごが滑らないためには、必要な静止摩擦力が最大静止摩擦力 $\\mu N_1$ 以下でなければならない。',
      ),
      eq('f \\le \\mu N_1 \\iff \\tan\\theta \\ge \\frac{\\frac{1}{2}mL + Md}{\\mu(m + M)L}'),
      ul(
        '人が乗っていない一様なはしごでは $\\tan\\theta \\ge \\dfrac{1}{2\\mu}$',
        '人が高く上る（$d$ が大きい）ほど、必要な摩擦力が大きくなり滑りやすい',
        '角 $\\theta$ が小さい（寝かせる）ほど滑りやすい',
      ),
      p(
        'つりあいが破れると、はしごの下端が壁から離れる向きに滑り出す。滑っている間は動摩擦力がはたらき、力学的エネルギーの一部が熱になる。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '剛体のつりあいは「水平・鉛直の力のつりあい」と「モーメントのつりあい」の 3 式',
        'モーメントの軸は、未知の力が集まる点（はしごなら下端）にとると式が簡単になる',
        '静止摩擦力は必要な分だけはたらく。限界のとき（滑り出す直前）だけ $f = \\mu N_1$ とおける',
        '重力は重心に 1 つの力としてはたらくと考えてよい（一様な棒なら中点）',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '人が乗っていないはしご（$M = 0$）が $\\mu = 0.40$ の床に立てかけてある。滑らずに立てかけられる最小の角は？',
        p(
          '$\\tan\\theta = 1/(2\\mu) = 1.25$ より $\\theta \\approx 51^\\circ$。人の質量を 0 にして、「滑り出す限界の角」を確かめよう。',
        ),
      ),
      question(
        '既定の条件（$\\theta = 60^\\circ$, $\\mu = 0.40$, $m = 10$ kg, $M = 50$ kg）で、人は下端から何 m まで上れるか。',
        p(
          '$\\frac{1}{2}mL + Md \\le \\mu(m + M)L\\tan\\theta$ より $d \\le (0.40 \\times 60 \\times 4 \\times 1.73 - 20)/50 \\approx 2.9$ m。人の位置を動かして、この位置を越えると滑り出すことを確かめよう。',
        ),
      ),
      question(
        '同じはしごで、人が上れる高さを増やすにはどうすればよいか。',
        p(
          '角 $\\theta$ を大きくする（立てる）か、摩擦係数の大きい床にする。はしごを重くしても効果がある（はしごの重心は中点で低い）。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        'つりあいの判定と力は、つりあいの 3 式から求めている。滑り出した後は、はしごが壁と床に接したまま動くとして、重心の並進と回転の運動方程式から垂直抗力と角加速度を連立して求め、RK4（刻み幅 $\\Delta t = 1$ ms）で解いている。上端が壁から離れた（$N_2 = 0$）か床に倒れた時点で止める。力とモーメントのつりあい、限界の角の公式、摩擦熱を含めたエネルギーの収支、摩擦がない場合の既知の解（$\\sin\\theta = \\frac{2}{3}\\sin\\theta_0$ で壁から離れる）との一致を自動テストで確認している。',
      ),
    ),
  );
}
