import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '万有引力と円軌道',
      p(
        '質量 $M$ の地球と質量 $m$ の衛星の間には、距離 $r$ の 2 乗に反比例する万有引力 $F = G\\dfrac{Mm}{r^2}$ がはたらく。地表では万有引力が重力 $mg$ に等しいので $GM = gR^2$（$R$ は地球の半径）。',
      ),
      p('半径 $r$ の円軌道では、万有引力が向心力になる。'),
      eq(
        'm\\frac{v^2}{r} = G\\frac{Mm}{r^2} \\quad\\Longrightarrow\\quad v = \\sqrt{\\frac{GM}{r}}, \\qquad T = 2\\pi\\sqrt{\\frac{r^3}{GM}}',
      ),
      p(
        '地表すれすれ（$r = R$）の円軌道の速さ $\\sqrt{gR} \\approx 7.9$ km/s を第一宇宙速度という。',
      ),
    ),
    section(
      '万有引力による位置エネルギーと脱出速度',
      p(
        '無限遠を基準とすると、万有引力による位置エネルギーは $U = -G\\dfrac{Mm}{r}$。力学的エネルギーが保存される。',
      ),
      eq('\\frac{1}{2}mv^2 - G\\frac{Mm}{r} = \\text{一定}'),
      p(
        '力学的エネルギーが $0$ 以上なら、衛星は無限遠まで飛び去る。$r_0$ から打ち出して脱出するのに必要な速さ（脱出速度）は',
      ),
      eq('v = \\sqrt{\\frac{2GM}{r_0}}'),
      p('地表では $\\sqrt{2gR} \\approx 11.2$ km/s（第二宇宙速度）。'),
    ),
    section(
      'ケプラーの法則',
      ul(
        '第 1 法則: 惑星（衛星）は、太陽（地球の中心）を 1 つの焦点とする楕円軌道を描く',
        '第 2 法則: 太陽と惑星を結ぶ線分が単位時間に掃く面積（面積速度）は一定',
        '第 3 法則: 周期 $T$ の 2 乗は楕円の長半径 $a$ の 3 乗に比例する（$T^2/a^3$ は一定）',
      ),
      p('面積速度一定から、近地点と遠地点の速さには次の関係がある。'),
      eq('\\frac{1}{2}r_{\\mathrm{p}}v_{\\mathrm{p}} = \\frac{1}{2}r_{\\mathrm{a}}v_{\\mathrm{a}}'),
      p(
        '楕円軌道の周期は、長半径 $a = (r_{\\mathrm{p}} + r_{\\mathrm{a}})/2$ を円の半径と見なした式になる。',
      ),
      eq('T = 2\\pi\\sqrt{\\frac{a^3}{GM}}, \\qquad \\frac{T^2}{a^3} = \\frac{4\\pi^2}{GM}'),
      p(
        '「面積速度」を表示すると、等しい時間（周期の 1/12）ごとに掃く扇形が塗り分けられる。近地点付近の扇形は細長く、遠地点付近は幅が広いが、面積はすべて等しい。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '楕円軌道の問題は「面積速度一定（近地点と遠地点）」と「力学的エネルギー保存」の 2 本を連立する',
        '万有引力の位置エネルギーは $-GMm/r$（負）。地表付近の $mgh$ とは基準が違う',
        '$GM$ が与えられていなければ $GM = gR^2$ を使う',
        '円軌道より速く打ち出すと打ち出した点が近地点、遅く打ち出すと遠地点になる',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '地球の中心から $2R$ の位置で円軌道を回るための速さはいくらか。',
        p(
          '$v = \\sqrt{GM/2R} = \\sqrt{gR/2} \\approx 5.6$ km/s。打ち出す速さを 5.6 km/s にして、軌道が円になることを確かめよう。',
        ),
      ),
      question(
        '同じ位置から脱出速度で打ち出すには、円軌道の速さの何倍が必要か。',
        p('$\\sqrt{2}$ 倍（約 7.9 km/s）。「この条件での値」で確かめよう。'),
      ),
      question(
        '打ち出す速さを変えて楕円の大きさを変えると、$T^2/a^3$ はどうなるか。',
        p('変わらない（$4\\pi^2/GM$ で一定）。「この条件での値」の $T^2/a^3$ を見比べよう。'),
      ),
    ),
    section(
      '数値計算について',
      p(
        '運動方程式 $m\\vec{a} = -GMm\\vec{r}/r^3$ を、刻み幅 $\\Delta t = 1$ s の吉田の 4 次シンプレクティック法で解いている（画面では 1 秒間に約 2000 秒進む）。ケプラー方程式による楕円軌道の解析解との一致、ケプラーの 3 法則、力学的エネルギーと面積速度の保存を自動テストで確認している。',
      ),
    ),
  );
}
