import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '復元力と運動方程式',
      p(
        'つりあいの位置を原点とし、右向きを正とする $x$ 軸をとる。ばねが自然長から $x$ だけ伸びているとき、物体には弾性力 $F=-kx$ がはたらく。変位と逆向きで、大きさが変位に比例する力を「復元力」という。',
      ),
      p('運動方程式は'),
      eq(
        'ma = -kx \\quad\\Longrightarrow\\quad a = -\\omega^2 x, \\qquad \\omega = \\sqrt{\\frac{k}{m}}',
      ),
      p('加速度が変位に比例し逆向きのとき、物体は単振動をする。$\\omega$ を角振動数という。'),
    ),
    section(
      '変位・速度・加速度',
      eq(
        '\\begin{aligned} x &= A\\sin(\\omega t + \\theta_0) \\\\ v &= A\\omega\\cos(\\omega t + \\theta_0) \\\\ a &= -A\\omega^2\\sin(\\omega t + \\theta_0) = -\\omega^2 x \\end{aligned}',
      ),
      ul(
        '速さが最大になるのはつりあいの位置（$x=0$）で、$v_{\\max} = A\\omega$',
        '加速度の大きさが最大になるのは振動の端（$x=\\pm A$）で、$a_{\\max} = A\\omega^2$',
        'グラフで見ると、$v$ は $x$ より位相が $\\pi/2$ 進み、$a$ は $x$ と逆位相',
      ),
    ),
    section(
      '周期と等時性',
      eq('T = \\frac{2\\pi}{\\omega} = 2\\pi\\sqrt{\\frac{m}{k}}'),
      p(
        '周期は質量 $m$ とばね定数 $k$ だけで決まり、振幅 $A$ にはよらない（等時性）。初期変位 $x_0$ のスライダーを動かしても周期が変わらないことを確かめよう。',
      ),
      p('振幅は初期条件で決まる: $A = \\sqrt{x_0^{\\,2} + (v_0/\\omega)^2}$。'),
    ),
    section(
      '等速円運動との関係',
      p(
        '半径 $A$ の円周上を角速度 $\\omega$ で等速円運動する点を、$x$ 軸に正射影した点の運動が単振動である。「参照円」を表示して、円周上の点と物体の動きが常にそろうことを確かめよう。',
      ),
    ),
    section(
      '力学的エネルギーの保存',
      p('弾性力は保存力なので、運動エネルギーと弾性エネルギーの和は一定に保たれる。'),
      eq('\\frac{1}{2}mv^2 + \\frac{1}{2}kx^2 = \\frac{1}{2}kA^2 = \\text{一定}'),
      p(
        'エネルギーのグラフで、$K$ と $U$ が周期 $T/2$ でやりとりしながら、和 $E$ が一定であることを確かめよう。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '鉛直につるしたばねでも、つりあいの位置を中心とする単振動になり、周期は同じ $T = 2\\pi\\sqrt{m/k}$（重力は振動の中心をずらすだけ）',
        '「周期」は $m$ と $k$、「振幅」は初期条件で決まる。問われている量がどちらで決まるかを区別する',
        '速さ・加速度の最大値は $A\\omega$、$A\\omega^2$。位置との対応（中心か端か）とセットで覚える',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '質量を 4 倍にすると、周期は何倍になるか。',
        p('$T \\propto \\sqrt{m}$ なので 2 倍。スライダーで $m$ を 1 kg → 4 kg にして確かめよう。'),
      ),
      question(
        '$m = 1$ kg, $k = 10$ N/m, $x_0 = 0.30$ m から静かに放した。速さが最大になる位置と、その速さは？',
        p(
          'つりあいの位置 $x = 0$ で最大。$v_{\\max} = A\\omega = 0.30 \\times \\sqrt{10} \\approx 0.95$ m/s。「現在の値」で確かめよう。',
        ),
      ),
      question(
        '変位が振幅の半分（$x = A/2$）のとき、運動エネルギーは力学的エネルギーの何割か。',
        p(
          '$U = \\frac{1}{2}k(A/2)^2 = \\frac{1}{4}\\cdot\\frac{1}{2}kA^2$ なので $U$ は全体の $1/4$、$K$ は $3/4$（7.5 割）。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        'このシミュレーションは運動方程式を刻み幅 $\\Delta t = 1$ ms の速度ベルレ法（シンプレクティック積分法）で解いている。長時間動かしても力学的エネルギーが増えたり減ったりし続けない性質がある。解析解・周期の公式・エネルギー保存との一致は自動テストで確認している。',
      ),
    ),
  );
}
