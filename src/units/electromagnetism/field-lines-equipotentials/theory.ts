import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '点電荷のつくる電場と電位',
      p(
        '電気量 $Q$ の点電荷から距離 $r$ の点の電場の強さ $E$ と電位 $V$（無限遠を基準）は、クーロンの法則の比例定数 $k = 9.0\\times10^9\\ \\mathrm{N\\cdot m^2/C^2}$ を使って',
      ),
      eq('E = k\\frac{|Q|}{r^2}, \\qquad V = k\\frac{Q}{r}'),
      p(
        '電場は正電荷から遠ざかる向き（負電荷なら近づく向き）。電荷が 2 つあるときは、それぞれがつくる電場・電位を足し合わせる（重ね合わせの原理）。',
      ),
      ul(
        '電場はベクトルなので、向きを考えて矢印として足す',
        '電位はスカラーなので、符号付きの数としてそのまま足す',
      ),
    ),
    section(
      '電気力線',
      ul(
        '電気力線の接線の向きが、その点の電場の向き',
        '正電荷から出て負電荷に入る。途中で交わったり枝分かれしたりしない',
        '電荷 $Q$ から出る本数は $Q$ に比例する（ガウスの法則では $Q/\\varepsilon_0$ 本）。この図では 1 nC あたり 4 本',
        '電気力線が密なところほど電場が強い',
      ),
    ),
    section(
      '等電位線',
      p(
        '電位が等しい点を結んだ線を等電位線という。この図では 25 V ごとに描いている（破線が 0 V）。',
      ),
      ul(
        '等電位線と電気力線は必ず直交する',
        '電場は電位の高い方から低い方へ向く',
        '等電位線の間隔が狭いところほど電場が強い。一様な電場なら $E = \\dfrac{V}{d}$',
      ),
    ),
    section(
      '電位差と仕事・エネルギー保存',
      p(
        '電荷 $q$ を電位 $V_1$ の点から電位 $V_2$ の点まで動かすとき、静電気力がする仕事は経路によらず電位差だけで決まる。',
      ),
      eq('W = q(V_1 - V_2)'),
      p(
        '静電気力は保存力なので、ほかに力がはたらかなければ、運動エネルギーと静電気力による位置エネルギー $U = qV$ の和が保存される。',
      ),
      eq('\\frac{1}{2}mv^2 + qV = \\text{一定}'),
      p(
        'グラフの「エネルギー」で $K$ と $U$ の和が一定であること、「電位 V」で正の試験電荷が電位の低い方へ進むことを確かめよう。等電位線に沿った移動では仕事は 0 である。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '電場はベクトル和、電位はスカラー和。電場は向きを、電位は符号を間違えやすい',
        '等量異符号（$+Q$, $-Q$）の中点: 電位は 0 だが、電場は 0 ではない（$+$ から $-$ の向き）',
        '等量同符号（$+Q$, $+Q$）の中点: 電場は 0 だが、電位は 0 ではない',
        '仕事 $W = q\\Delta V$ や速さを問われたら、運動の途中を追わずにエネルギー保存で解く',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$Q_A = 2.0$ nC, $Q_B = -2.0$ nC, $d = 0.20$ m のとき、中点 M の電位と電場の強さは？',
        p(
          '電位は $k\\frac{Q}{0.10} + k\\frac{-Q}{0.10} = 0$ V。電場は両方とも B の向きで、$2 \\times k\\frac{Q}{(0.10)^2} = 3.6\\times10^3$ V/m。「この条件での値」で確かめよう。',
        ),
      ),
      question(
        '$Q_A = Q_B = 2.0$ nC にすると、中点 M の電場と電位はどうなるか。',
        p(
          '電場は打ち消し合って 0、電位は $2 \\times k\\frac{Q}{0.10} = 3.6\\times10^2$ V。中点の近くで等電位線が「×」の形に交わることにも注目しよう。',
        ),
      ),
      question(
        '試験電荷（$q = 1.0$ nC）が電位 100 V の点から 0 V の点まで動いた。運動エネルギーはいくら増えたか。',
        p(
          '$W = q(V_1 - V_2) = 1.0\\times10^{-9} \\times 100 = 1.0\\times10^{-7}$ J $= 0.10$ μJ。グラフで $V$ と $K$ の変化を読み取って確かめよう。',
        ),
      ),
      question(
        '静かに放した試験電荷は、電気力線に沿って動くか。',
        p(
          '動き始めの向きは電場（電気力線の接線）の向きだが、物体には慣性があるので、電気力線が曲がっているところでは外側にずれていく。「軌跡」を表示して電気力線と比べよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '試験電荷の運動方程式 $ma = qE$ は速度ベルレ法（シンプレクティック積分法）で解いている。電荷に近づくと力が急に大きくなるので、近さと速さに応じて刻み幅を自動で細かくしている。電気力線は電場の向きを 4 次のルンゲ＝クッタ法でたどり、等電位線は格子点の電位からマーチングスクエア法で求めている。公式・解析解・エネルギー保存・直交性との一致は自動テストで確認している。',
      ),
    ),
  );
}
