import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '充電の過程',
      p(
        'スイッチ S を a 側に入れると、電池・抵抗・コンデンサーの直列回路になる。キルヒホッフの第 2 法則より、どの時刻でも',
      ),
      eq('E = RI + \\frac{q}{C}'),
      ul(
        'スイッチを入れた直後は $q = 0$ なので、コンデンサーは導線と同じに見え、電流は $I_0 = E/R$',
        'コンデンサーに電荷がたまるにつれて $q/C$ が大きくなり、電流は小さくなる',
        '十分時間がたつと $I = 0$（コンデンサーは断線と同じ）で、電気量は $Q = CE$',
      ),
      p('電気量と電流は指数関数で変化する。'),
      eq(
        'q = CE\\left(1 - e^{-t/\\tau}\\right), \\qquad I = \\frac{E}{R}e^{-t/\\tau}, \\qquad \\tau = RC',
      ),
    ),
    section(
      '放電の過程',
      p(
        'S を b 側に切り替えると、電池が外れてコンデンサーと抵抗だけの回路になり、コンデンサーが放電する。電流の向きは充電のときと逆になる。',
      ),
      eq('q = Q_0 e^{-t/\\tau}, \\qquad I = -\\frac{Q_0}{RC}e^{-t/\\tau}'),
    ),
    section(
      '時定数 τ = RC',
      p(
        '時定数 $\\tau$ は変化の速さの目安で、$\\tau$ 秒ごとに「残りの変化」が $1/e \\approx 0.37$ 倍になる。充電なら $t = \\tau$ で最終値の約 63%、放電なら約 37% になる。$R$ や $C$ を大きくすると、ゆっくり充電・放電する。',
      ),
    ),
    section(
      'エネルギーの収支',
      p(
        '電池がした仕事 $W$ は、コンデンサーの静電エネルギー $U$ と抵抗のジュール熱 $Q$ に分かれる。',
      ),
      eq('W = U + Q, \\qquad U = \\frac{q^2}{2C}'),
      p(
        '充電しきるまでに電池は電気量 $CE$ を電位差 $E$ だけ運ぶので $W = CE^2$。一方 $U = \\frac{1}{2}CE^2$ なので、残りの半分 $\\frac{1}{2}CE^2$ は抵抗の大きさによらずジュール熱になる。棒グラフで確かめよう。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        'スイッチを入れた直後のコンデンサーは「導線」、十分時間がたった後は「断線」とみなして回路を解く',
        'コンデンサーの電圧（電気量）は急に変わらない。スイッチを切り替えた直後の電流は、直前の電圧から求める',
        '充電で電池がする仕事 $CE^2$ の半分が熱になる（$R$ によらない）',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$E = 6.0$ V, $R = 5.0$ kΩ, $C = 200$ μF のとき、スイッチを入れた直後の電流と時定数は？',
        p(
          '$I_0 = E/R = 1.2$ mA、$\\tau = RC = 5.0\\times10^3 \\times 200\\times10^{-6} = 1.0$ s。',
        ),
      ),
      question(
        '充電しきったときの電気量と静電エネルギーは？ また、それまでに発生したジュール熱は？',
        p(
          '$Q = CE = 1.2$ mC、$U = \\frac{1}{2}CE^2 = 3.6$ mJ。ジュール熱も 3.6 mJ（電池の仕事 7.2 mJ の半分）。',
        ),
      ),
      question(
        '充電の途中でスイッチを b 側に切り替えた。直後の電流の大きさは？',
        p(
          'コンデンサーの電圧 $V_C$ は急には変わらないので、直後の電流は $V_C/R$（向きは充電のときと逆）。「現在の値」の $V_C$ を使って確かめよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '回路の方程式 $R\\dfrac{dq}{dt} = E - \\dfrac{q}{C}$ を、ジュール熱・電池の仕事の積算と合わせて刻み幅 $\\Delta t = 1$ ms の 4 次のルンゲ＝クッタ法で解いている。解析解（指数関数）・エネルギー収支との一致は自動テストで確認している。',
      ),
    ),
  );
}
