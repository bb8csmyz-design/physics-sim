import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '交流と実効値',
      p(
        '交流電源の電圧は $v = V_0\\sin\\omega t$（$\\omega = 2\\pi f$）のように時間とともに正弦波で変化する。',
      ),
      p(
        '抵抗で消費される電力の平均が直流と同じになる値を実効値という。正弦波では最大値の $1/\\sqrt{2}$ 倍。',
      ),
      eq('V_e = \\frac{V_0}{\\sqrt{2}}, \\qquad I_e = \\frac{I_0}{\\sqrt{2}}'),
      p('家庭用の「100 V」は実効値で、最大値は約 141 V である。'),
    ),
    section(
      '抵抗・コイル・コンデンサーの電圧と電流',
      ul(
        '抵抗: $v_R = Ri$。電圧と電流は同位相',
        'コイル: 誘導リアクタンス $X_L = \\omega L$。電圧は電流より位相が $\\pi/2$ 進む（周波数が高いほど電流を通しにくい）',
        'コンデンサー: 容量リアクタンス $X_C = \\dfrac{1}{\\omega C}$。電圧は電流より位相が $\\pi/2$ 遅れる（周波数が高いほど電流を通しやすい）',
      ),
      p(
        'グラフの「電圧」で $v_R$, $v_L$, $v_C$ の山の位置のずれを、「ベクトル図」で矢印の向きの違いを確かめよう。',
      ),
    ),
    section(
      'インピーダンスと位相差',
      p(
        '直列回路では電流が共通なので、各素子の電圧をベクトル図で足し合わせると電源電圧になる。$V_L$ と $V_C$ は逆向きなので打ち消し合う。',
      ),
      eq(
        'Z = \\sqrt{R^2 + \\left(\\omega L - \\frac{1}{\\omega C}\\right)^2}, \\qquad I_0 = \\frac{V_0}{Z}',
      ),
      eq('\\tan\\varphi = \\frac{\\omega L - \\dfrac{1}{\\omega C}}{R}'),
      p(
        '$\\varphi > 0$ なら電流は電源電圧より $\\varphi$ だけ遅れる（コイルの性質が強い）。$\\varphi < 0$ なら進む。',
      ),
    ),
    section(
      '消費電力',
      p(
        'コイルとコンデンサーは、1 周期の間にエネルギーを蓄えては返すだけで、平均すると電力を消費しない。電力を消費するのは抵抗だけである。',
      ),
      eq('\\overline{P} = V_eI_e\\cos\\varphi = I_e^{\\,2}R'),
      p(
        '$\\cos\\varphi$ を力率という。グラフの「電力」で、瞬間の電力 $p = vi$ が負になる時間があることも確かめよう。',
      ),
    ),
    section(
      '共振',
      p(
        '$\\omega L = \\dfrac{1}{\\omega C}$ となる周波数では、$V_L$ と $V_C$ がちょうど打ち消し合い、$Z = R$ が最小になって電流が最大になる。',
      ),
      eq('f_0 = \\frac{1}{2\\pi\\sqrt{LC}}'),
      p(
        'これは LC 回路の電気振動の固有周波数と同じである。周波数のスライダーを動かして、$f_0$ の近くで電流が大きくなり、位相差が 0 になることを確かめよう。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '電圧の位相: コイルは電流より $\\pi/2$ 進み、コンデンサーは $\\pi/2$ 遅れる（「コイルは進み、コンデンサーは遅れ」）',
        '$X_L = \\omega L$ は周波数に比例、$X_C = 1/(\\omega C)$ は反比例。直流（$\\omega = 0$）ではコイルは導線、コンデンサーは断線',
        '消費電力は抵抗だけで、$\\overline{P} = I_e^{\\,2}R$。実効値を使う',
        '共振周波数 $f_0 = \\dfrac{1}{2\\pi\\sqrt{LC}}$ ではインピーダンスが $R$ になる',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '既定の条件（$V_e = 100$ V, $f = 50$ Hz, $R = 20$ Ω, $L = 100$ mH, $C = 200$ μF）で、$X_L$, $X_C$, $Z$ は？',
        p(
          '$X_L = 2\\pi\\times50\\times0.10 \\approx 31.4$ Ω、$X_C = \\dfrac{1}{2\\pi\\times50\\times200\\times10^{-6}} \\approx 15.9$ Ω、$Z = \\sqrt{20^2 + 15.5^2} \\approx 25.3$ Ω。',
        ),
      ),
      question(
        'そのときの電流の実効値と、平均の消費電力は？',
        p(
          '$I_e = 100/25.3 \\approx 3.95$ A、$\\overline{P} = I_e^{\\,2}R \\approx 312$ W。「この条件での値」で確かめよう。',
        ),
      ),
      question(
        'この回路の共振周波数は？ 周波数をそこに合わせると電流の実効値はいくらになるか。',
        p(
          '$f_0 = \\dfrac{1}{2\\pi\\sqrt{0.10\\times200\\times10^{-6}}} \\approx 35.6$ Hz。このとき $Z = R = 20$ Ω なので $I_e = 5.0$ A。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '回路の方程式 $v = Ri + L\\dfrac{di}{dt} + \\dfrac{q}{C}$ を、刻み幅 $\\Delta t = 20$ μs の 4 次のルンゲ＝クッタ法で解いている。はじめは定常状態から始めるが、「電源を入れた瞬間から始める」をオンにすると過渡現象が減衰して定常状態に近づく様子が見られる。実際の 1/100 の速さで再生している。定常状態の解析解・実効値・消費電力・エネルギー収支との一致は自動テストで確認している。',
      ),
    ),
  );
}
