import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '電気振動のしくみ',
      p(
        '電圧 $V_0$ に充電したコンデンサーをコイルにつなぐと、コンデンサーが放電して電流が流れ始める。コイルは電流の変化を妨げるので、電荷が 0 になっても電流は流れ続け、今度は逆向きに充電する。これをくり返すのが電気振動である。',
      ),
      ul(
        '$q$ が 0 のとき電流 $i$ の大きさが最大、$i$ が 0 のとき $|q|$ が最大',
        '電流は電気量より位相が $\\pi/2$ ずれている（グラフで確かめよう）',
      ),
    ),
    section(
      '周期と固有周波数',
      p('コンデンサーの電圧とコイルの自己誘導起電力が等しいことから'),
      eq('\\frac{q}{C} = L\\frac{\\Delta i}{\\Delta t}, \\qquad i = -\\frac{\\Delta q}{\\Delta t}'),
      p('これはばねの単振動 $ma = -kx$ と同じ形の式で、$q = Q_0\\cos\\omega t$ となる。'),
      eq(
        '\\omega = \\frac{1}{\\sqrt{LC}}, \\qquad T = 2\\pi\\sqrt{LC}, \\qquad f = \\frac{1}{2\\pi\\sqrt{LC}}',
      ),
      p('周期ははじめの電圧によらない（ばねの等時性と同じ）。'),
    ),
    section(
      'エネルギー保存',
      p(
        '抵抗がなければ、コンデンサーの静電エネルギー（電場のエネルギー）とコイルのエネルギー（磁場のエネルギー）の和が保存される。',
      ),
      eq('\\frac{q^2}{2C} + \\frac{1}{2}Li^2 = \\frac{1}{2}CV_0^{\\,2} = \\text{一定}'),
      p('よって電流の最大値は $\\frac{1}{2}LI_0^{\\,2} = \\frac{1}{2}CV_0^{\\,2}$ より'),
      eq('I_0 = V_0\\sqrt{\\frac{C}{L}} = Q_0\\,\\omega'),
      p(
        'エネルギーは周期 $T/2$ で電場と磁場の間を行き来する。棒グラフとエネルギーのグラフで確かめよう。',
      ),
    ),
    section(
      'ばねの単振動との対応',
      ul(
        '電気量 $q$ ↔ 変位 $x$、電流 $i$ ↔ 速度 $v$',
        '自己インダクタンス $L$ ↔ 質量 $m$（変化しにくさ）、$1/C$ ↔ ばね定数 $k$',
        '静電エネルギー $\\frac{q^2}{2C}$ ↔ 弾性エネルギー $\\frac{1}{2}kx^2$、磁場のエネルギー $\\frac{1}{2}Li^2$ ↔ 運動エネルギー $\\frac{1}{2}mv^2$',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '周期 $T = 2\\pi\\sqrt{LC}$ は、ばねの $T = 2\\pi\\sqrt{m/k}$ と対応させて覚える',
        '電流の最大値はエネルギー保存 $\\frac{1}{2}CV_0^{\\,2} = \\frac{1}{2}LI_0^{\\,2}$ から求める',
        'スイッチを閉じてから電流が最大になるまでの時間は $T/4$、コンデンサーの電荷が逆向きに最大になるまでは $T/2$',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$L = 50$ mH, $C = 20$ μF のとき、周期と固有周波数は？',
        p(
          '$T = 2\\pi\\sqrt{50\\times10^{-3}\\times20\\times10^{-6}} = 2\\pi\\times10^{-3}$ s $\\approx 6.3$ ms、$f \\approx 159$ Hz。',
        ),
      ),
      question(
        '$V_0 = 10$ V のとき、電流の最大値は？',
        p(
          '$I_0 = V_0\\sqrt{C/L} = 10\\times\\sqrt{20\\times10^{-6}/(50\\times10^{-3})} = 0.20$ A $= 200$ mA。',
        ),
      ),
      question(
        '$C$ を 4 倍にすると、周期と電流の最大値はどうなるか。',
        p(
          '周期は 2 倍。電流の最大値も $\\sqrt{C}$ に比例するので 2 倍（蓄えるエネルギーが 4 倍になるため）。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '$d^2q/dt^2 = -q/(LC)$ を刻み幅 $\\Delta t = 10$ μs の速度ベルレ法（シンプレクティック積分法）で解いている。長時間動かしてもエネルギーが増えたり減ったりし続けない。振動が速い（周期 2〜20 ms）ので、実際の 1/500 の速さで再生している。解析解・周期の公式・エネルギー保存との一致は自動テストで確認している。',
      ),
    ),
  );
}
