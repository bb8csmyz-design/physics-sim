import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      'ファラデーの電磁誘導の法則',
      p(
        '回路を貫く磁束 $\\Phi$ が変化すると、回路に誘導起電力が生じる。その大きさは磁束の時間変化率に等しい。',
      ),
      eq('V = \\left|\\frac{\\Delta\\Phi}{\\Delta t}\\right|'),
      p(
        '棒が速さ $v$ で動くと、回路の面積は 1 秒あたり $vl$ ずつ増えるので、磁束は 1 秒あたり $vBl$ 増える。よって誘導起電力は',
      ),
      eq('V = vBl, \\qquad I = \\frac{V}{R} = \\frac{vBl}{R}'),
    ),
    section(
      'レンツの法則',
      p(
        '誘導電流は、磁束の変化を妨げる向きに流れる。この図では右へ動くと上向きの磁束が増えるので、それを打ち消す下向きの磁場をつくる向き（真上から見て時計回り）に電流が流れる。',
      ),
      p(
        '電流が流れる棒は磁場から力 $IBl$ を受ける。その向きは必ず棒の運動を妨げる向き（ブレーキ）になる。',
      ),
    ),
    section(
      '運動方程式と終端速度',
      eq('m\\frac{\\Delta v}{\\Delta t} = F - \\frac{B^2l^2}{R}v'),
      p(
        '速くなるほどブレーキの力が強くなり、やがて外力とつりあって等速になる（終端速度）。終端速度との差は時定数 $\\tau$ で指数関数的に小さくなる。',
      ),
      eq('v_f = \\frac{FR}{B^2l^2}, \\qquad \\tau = \\frac{mR}{B^2l^2}'),
    ),
    section(
      'エネルギーの収支',
      p(
        '外力がした仕事 $W$ は、棒の運動エネルギーの増加と抵抗で発生するジュール熱 $Q$ に分かれる。',
      ),
      eq('W = \\Delta K + Q'),
      p(
        '終端速度では運動エネルギーは変わらないので、外力の仕事率 $Fv_f$ がすべて抵抗の消費電力 $I^2R$ になる。「エネルギー」のグラフで $W$ が $K$ と $Q$ の和に等しいことを確かめよう。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '誘導起電力 $vBl$ → 電流 $I = vBl/R$ → 力 $IBl$ の順に、向きと大きさをセットで求める',
        '終端速度は「力のつりあい」$F = \\dfrac{B^2l^2}{R}v_f$ から。仕事率のつりあい $Fv_f = I^2R$ でも求められる',
        '流れた電気量は $q = \\dfrac{\\Delta\\Phi}{R}$（途中の速さによらない）',
        '外力がなく初速度だけのとき、止まるまでのジュール熱の合計は $\\dfrac{1}{2}mv_0^{\\,2}$',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '既定の条件（$B = 0.50$ T, $l = 0.50$ m, $R = 1.0$ Ω, $F = 0.10$ N）で、終端速度と、そのときの誘導起電力・電流は？',
        p(
          '$v_f = \\dfrac{FR}{B^2l^2} = \\dfrac{0.10\\times1.0}{(0.25)^2} = 1.6$ m/s。$V = v_fBl = 0.40$ V、$I = 0.40$ A。「この条件での値」で確かめよう。',
        ),
      ),
      question(
        '抵抗 $R$ を 2 倍にすると、終端速度はどうなるか。',
        p('電流が流れにくくなりブレーキが弱まるので、終端速度は 2 倍になる（時定数も 2 倍）。'),
      ),
      question(
        '外力を 0 にして初速度 2.0 m/s を与えた。止まるまでに発生するジュール熱は？（$m = 0.10$ kg）',
        p(
          '運動エネルギーがすべて熱になるので $\\frac{1}{2}\\times0.10\\times2.0^2 = 0.20$ J。グラフで $Q$ が近づく値を確かめよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '速度に比例するブレーキの力を含む運動方程式を、ジュール熱・外力の仕事の積算と合わせて刻み幅 $\\Delta t = 1$ ms の 4 次のルンゲ＝クッタ法で解いている。解析解（指数関数）・エネルギー収支・ファラデーの法則との一致は自動テストで確認している。',
      ),
    ),
  );
}
