import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      'ローレンツ力',
      p(
        '磁束密度 $B$ の磁場の中を、電荷 $q$ の粒子が磁場に垂直に速さ $v$ で動くと、速度と磁場の両方に垂直な向きにローレンツ力を受ける。',
      ),
      eq('f = qvB'),
      p(
        '正電荷の場合、力の向きはフレミングの左手の法則（中指を速度の向き＝電流の向き）で決まる。負電荷では逆向きになる。ローレンツ力は常に速度に垂直なので、仕事をしない（速さは変わらない）。',
      ),
    ),
    section(
      '磁場中の等速円運動',
      p('ローレンツ力が向心力となって等速円運動をする。運動方程式（円の中心方向）は'),
      eq('m\\frac{v^2}{r} = qvB \\quad\\Longrightarrow\\quad r = \\frac{mv}{qB}'),
      eq('T = \\frac{2\\pi r}{v} = \\frac{2\\pi m}{qB}'),
      ul(
        '回転半径 $r$ は速さ $v$ に比例する',
        '周期 $T$ は速さによらない（サイクロトロンが一定の周波数で粒子を加速できる理由）',
        '比電荷 $q/m$ が大きいほど小さな円を短い周期で回る',
      ),
    ),
    section(
      '電場中の運動',
      p(
        '一様な電場 $E$ の中では、粒子は一定の力 $qE$ を受けて等加速度運動をする。初速度が電場に垂直なら、重力の中の水平投射と同じ放物線を描く（磁束密度を 0 にして確かめよう）。',
      ),
      eq('x = v_0 t, \\qquad y = \\frac{1}{2}\\frac{qE}{m}t^2'),
      p(
        '電場の力は仕事をするので、運動エネルギーと電場による位置エネルギー $qV$ の和が保存される（この図では $V = -Ey$）。',
      ),
    ),
    section(
      '電場と磁場の両方があるとき',
      p('電場の力 $qE$ とローレンツ力 $qvB$ が逆向きでつりあうと、粒子は直進する。'),
      eq('qE = qvB \\quad\\Longrightarrow\\quad v = \\frac{E}{B}'),
      p(
        'この速さの粒子だけが直進して小さな穴を通り抜けるので、速度選別器として使われる。速さが $E/B$ と違うと、粒子は円運動をしながら $x$ 方向に平均の速さ $E/B$ で流されていく（ドリフト）。静止状態から放すと、サイクロイドという曲線を描く。',
      ),
    ),
    section(
      'グラフと数値の読み方',
      ul(
        '「v-t」で、電場がないときは $v_x$, $v_y$ が周期 $T$ の正弦波になり、速さは一定であることを確かめる',
        '「エネルギー」で、磁場だけなら $K$ が一定、電場があっても $K + U$ が一定であることを確かめる',
        '「この条件での値」の回転半径と周期を、軌跡の大きさや $v$-$t$ グラフの周期と比べる',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '円運動の問題は「ローレンツ力 = 向心力」の式から $r = \\dfrac{mv}{qB}$ を導けるようにする',
        '周期 $T = \\dfrac{2\\pi m}{qB}$ は速さによらない。半周で出ていく問題では、かかる時間は $T/2$',
        '電子（負電荷）は回る向きが逆。向きはフレミングの左手の法則で、電流の向き＝正電荷の動く向きに注意',
        '磁場は仕事をしないので、磁場の中で速さ（運動エネルギー）は変わらない',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$m = 2.0$ g, $q = 2.0$ mC, $B = 1.0$ T, $v_0 = 1.0$ m/s のとき、回転半径と周期は？',
        p(
          '$r = \\dfrac{mv}{qB} = \\dfrac{2.0\\times10^{-3}\\times1.0}{2.0\\times10^{-3}\\times1.0} = 1.0$ m、$T = \\dfrac{2\\pi m}{qB} = 2\\pi \\approx 6.3$ s。',
        ),
      ),
      question(
        '初速度を 2 倍にすると、回転半径と周期はどうなるか。',
        p('半径は 2 倍、周期は変わらない。スライダーで確かめよう。'),
      ),
      question(
        '電荷を負にすると、粒子はどちら回りに回るか。',
        p(
          '正電荷で $B > 0$（⊙）のときは時計回り。負電荷では力の向きが逆になるので反時計回りになる。',
        ),
      ),
      question(
        '$B = 1.0$ T, $E = 1.0$ V/m のとき、粒子が直進する初速度は？',
        p('$v = E/B = 1.0$ m/s。このとき、電荷や質量を変えても直進し続ける。'),
      ),
    ),
    section(
      '数値計算について',
      p(
        'ローレンツ力は速度によって変わる力なので、運動方程式を刻み幅 $\\Delta t = 1$ ms の 4 次のルンゲ＝クッタ法で解いている。解析解（円運動・サイクロイド・放物運動）、回転半径と周期の公式、エネルギー保存との一致は自動テストで確認している。',
      ),
    ),
  );
}
