import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '自己誘導',
      p(
        'コイルに流れる電流が変化すると、コイル自身を貫く磁束が変化するので、その変化を妨げる向きに誘導起電力が生じる（自己誘導）。その大きさは電流の変化率に比例する。',
      ),
      eq('V_L = L\\frac{\\Delta I}{\\Delta t}'),
      p('比例定数 $L$ を自己インダクタンス（単位 H: ヘンリー）という。'),
    ),
    section(
      'スイッチを入れたとき（a 側）',
      p('キルヒホッフの第 2 法則より'),
      eq('E = RI + L\\frac{\\Delta I}{\\Delta t}'),
      ul(
        '直後は $I = 0$。電流を急に増やさないよう、コイルに電池と同じ大きさ $E$ の起電力が逆向きに生じる（コイルは断線と同じ）',
        '電流はしだいに増え、十分時間がたつと $I = E/R$ で一定になる。このとき $V_L = 0$（コイルは導線と同じ）',
      ),
      eq('I = \\frac{E}{R}\\left(1 - e^{-t/\\tau}\\right), \\qquad \\tau = \\frac{L}{R}'),
    ),
    section(
      'スイッチを b 側に切り替えたとき',
      p(
        '電池を外しても、コイルは電流を保とうとするので、電流はすぐには 0 にならず、同じ向きに流れ続けてから減衰する。このときコイルが電池のかわりになって抵抗に電流を流す。',
      ),
      eq('I = I_0\\, e^{-t/\\tau}'),
    ),
    section(
      'コイルに蓄えられるエネルギー',
      p('電流 $I$ が流れているコイルには、磁場のエネルギーとして'),
      eq('U = \\frac{1}{2}LI^2'),
      p(
        'が蓄えられている。a 側では電池の仕事 $W$ がコイルのエネルギー $U$ とジュール熱 $Q$ に分かれ（$W = U + Q$）、b 側に切り替えると $U$ がすべてジュール熱になる。棒グラフとエネルギーのグラフで確かめよう。',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        'スイッチを入れた直後のコイルは「断線」、十分時間がたった後は「導線」とみなして回路を解く（コンデンサーと逆）',
        'コイルの電流は急に変わらない。スイッチを切り替えた直後の電流は直前の電流と同じ',
        '回路を急に切ると、電流を保とうとして非常に大きな誘導起電力が生じる（火花が出る）',
        'エネルギー $\\frac{1}{2}LI^2$ は、コンデンサーの $\\frac{1}{2}CV^2$ と対応させて覚える',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$E = 6.0$ V, $R = 20$ Ω, $L = 400$ mH のとき、時定数と十分時間がたったときの電流は？',
        p('$\\tau = L/R = 0.020$ s $= 20$ ms、$I = E/R = 0.30$ A。'),
      ),
      question(
        'そのときコイルに蓄えられているエネルギーは？',
        p(
          '$U = \\frac{1}{2}LI^2 = \\frac{1}{2}\\times0.40\\times0.30^2 = 1.8\\times10^{-2}$ J $= 18$ mJ。',
        ),
      ),
      question(
        'スイッチを入れた直後に抵抗に流れる電流と、コイルの電圧は？',
        p(
          '電流は 0、コイルの電圧は $E = 6.0$ V。グラフの「電圧」で、$V_L$ が $E$ から始まって 0 に近づくことを確かめよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '回路の方程式 $L\\dfrac{dI}{dt} = E - RI$ を、ジュール熱・電池の仕事の積算と合わせて刻み幅 $\\Delta t = 20$ μs の 4 次のルンゲ＝クッタ法で解いている。変化が速い（数〜数十 ms）ので、実際の 1/50 の速さで再生している。解析解・エネルギー収支との一致は自動テストで確認している。',
      ),
    ),
  );
}
