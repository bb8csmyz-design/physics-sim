import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '光子と光電効果',
      p(
        '金属に振動数の大きい光を当てると、金属の表面から電子が飛び出す。これを光電効果、飛び出した電子を光電子という。アインシュタインは、光は振動数 $\\nu$ に応じたエネルギーをもつ粒（光子）の集まりだと考えた（光量子仮説）。',
      ),
      eq('E = h\\nu = \\frac{hc}{\\lambda}, \\qquad h = 6.63\\times10^{-34}\\ \\text{J·s}'),
      p(
        '金属内の電子を外に取り出すのに必要な最小のエネルギーを仕事関数 $W$ という。光子 1 個のエネルギーを 1 個の電子が受け取り、そのうち $W$ を使って表面から出るので、飛び出した電子の運動エネルギーの最大値は',
      ),
      eq('K_{\\max} = \\frac{1}{2}mv_{\\max}^2 = h\\nu - W'),
      p(
        'となる（アインシュタインの光電方程式）。右側の棒グラフで、$h\\nu$ が $W$ と $K_{\\max}$ に分かれることを確かめよう。',
      ),
    ),
    section(
      '限界振動数と限界波長',
      p(
        '$h\\nu < W$ の光子では電子は外に出られない。光電効果が起こる最小の振動数（限界振動数）と最大の波長（限界波長）は',
      ),
      eq('\\nu_0 = \\frac{W}{h}, \\qquad \\lambda_0 = \\frac{c}{\\nu_0} = \\frac{hc}{W}'),
      p(
        '振動数が $\\nu_0$ より小さい光は、どんなに強くしても光電子を出さない。光の強さは光子の数を、振動数は光子 1 個のエネルギーを決めると考えると説明できる。',
      ),
    ),
    section(
      '光電流と阻止電圧',
      p(
        '陰極 K の電位を基準にした陽極 P の電位を $V$ とする。$V>0$ なら飛び出した光電子はすべて陽極に集まり、電流は一定の値（飽和電流 $I_0$）になる。毎秒 $N$ 個の光子が当たり、1 個の光子が 1 個の電子を飛び出させるとすると',
      ),
      eq('I_0 = eN, \\qquad N = \\frac{P}{h\\nu}\\quad(P\\text{ は光の仕事率})'),
      p(
        '$V<0$ にすると電子は押し返され、運動エネルギーの小さい電子から陽極に届かなくなる。運動エネルギーが最大の電子も届かなくなる電圧の大きさ $V_0$ を阻止電圧といい、',
      ),
      eq('eV_0 = K_{\\max} = h\\nu - W'),
      p(
        'の関係がある。「I-V 特性」のグラフで、$V = -V_0$ で電流が 0 になることを確かめよう。電圧の単位で表すと、$K_{\\max}$ を eV で表した数値がそのまま $V_0$（V）になる。',
      ),
    ),
    section(
      'グラフの読み方',
      ul(
        'I-V 特性: 横軸が陽極の電位 $V$、縦軸が光電流 $I$。右側の平らな部分の高さが飽和電流 $I_0$、電流が 0 になる点が $-V_0$',
        'K_max-ν: $K_{\\max} = h\\nu - W$ の直線。傾きはプランク定数 $h$（金属によらない）、横軸との交点が限界振動数 $\\nu_0$、縦軸の切片が $-W$',
        'I-t: 陽極に届いた電子を数えて求めた電流（測定値）と理論値。電子は確率的に飛び出すので、測定値は理論値のまわりでゆらぐ',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '振動数（波長）を変えずに光を強くすると、光子の数が増えて飽和電流が比例して増える。$K_{\\max}$ と阻止電圧 $V_0$ は変わらない',
        '振動数を大きくすると $K_{\\max}$ と $V_0$ が大きくなる。光の仕事率が同じなら光子 1 個のエネルギーが増える分だけ光子の数は減り、飽和電流は小さくなる',
        '$1\\ \\text{eV} = 1.6\\times10^{-19}$ J。光子のエネルギーは $E\\,[\\text{eV}] \\approx 1240 / \\lambda\\,[\\text{nm}]$ で手早く求められる',
        '$K_{\\max}$-$\\nu$ グラフは金属を変えると平行移動するだけ（傾き $h$ は共通）',
        '「限界振動数がある」「$K_{\\max}$ が光の強さによらない」「光を当てるとすぐに電子が出る」ことは、光を波と考えると説明できず、光子の考えで説明できる',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '波長 400 nm の光をナトリウム（$W = 2.3$ eV）に当てた。光電子の最大運動エネルギーと阻止電圧は？',
        p(
          '$h\\nu = 1240/400 \\approx 3.10$ eV なので $K_{\\max} = 3.10 - 2.3 = 0.80$ eV、阻止電圧は $V_0 = 0.80$ V。陽極の電位を $-0.80$ V にすると電流が 0 になることを確かめよう。',
        ),
      ),
      question(
        '光の強さを 2 倍にすると、I-V 特性のグラフはどう変わるか。',
        p(
          '飽和電流が 2 倍になり、電流が 0 になる電圧 $-V_0$ は変わらない。光の強さ $P$ を 100 μW → 200 μW にして確かめよう。',
        ),
      ),
      question(
        '仕事関数 2.3 eV の金属で光電効果が起こる最も長い波長は？',
        p(
          '$\\lambda_0 = hc/W \\approx 1240/2.3 \\approx 539$ nm。波長を 535 nm と 540 nm にして、光電子が出るかどうかが切り替わることを確かめよう。',
        ),
      ),
      question(
        '光の仕事率 $P$ を一定にしたまま波長を短くすると、飽和電流はどうなるか。',
        p(
          '光子 1 個のエネルギー $h\\nu$ が大きくなるので、毎秒当たる光子の数 $N = P/h\\nu$ が減り、飽和電流 $I_0 = eN$ は小さくなる（$K_{\\max}$ は大きくなる）。「この条件での値」の光子の数と飽和電流で確かめよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '光電子は乱数を使って確率的に飛び出させている（運動エネルギーは 0〜$K_{\\max}$ に一様、向きは余弦則に従う）。画面の点 1 個は $2\\times10^5$ 個の電子を表す。極板間の一様な電場の中の運動は等加速度運動の式で厳密に計算し、陽極に届いた点を数えて光電流を求めている。時間は 1 秒で 20 ns 進む速さで表示している。平行平板の理想的な光電管なので $V \\geq 0$ ですぐに飽和電流になる（実際の光電管では電極の形などのため、$V>0$ の範囲で少しずつ電流が増えてから飽和する）。',
      ),
      p(
        '光電方程式・限界振動数・阻止電圧・飽和電流の公式との一致、陽極に届く電子の割合と理論式の一致、阻止電圧で電流が 0 になることは自動テストで確認している。',
      ),
    ),
  );
}
