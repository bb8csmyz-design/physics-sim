import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '放射性崩壊',
      p(
        '不安定な原子核は、放射線を出してほかの原子核に変わる（放射性崩壊）。どの原子核がいつ崩壊するかは前もって決まっておらず、確率的に起こる。崩壊していない原子核は、それまでの経過時間によらず、単位時間あたり一定の確率 $\\lambda$（崩壊定数）で崩壊する。',
      ),
      ul(
        'α 崩壊: ヘリウム原子核 ${}^4_2\\text{He}$ を放出。質量数が 4、原子番号が 2 減る',
        'β 崩壊: 原子核内の中性子が陽子に変わり、電子を放出。質量数は変わらず、原子番号が 1 増える',
        'γ 線の放出: 励起状態の原子核が電磁波を出す。質量数・原子番号は変わらない',
      ),
    ),
    section(
      '半減期と崩壊の式',
      p(
        '時刻 $t$ に残っている原子核の数を $N$ とすると、時間 $\\Delta t$ の間に崩壊する数は $\\lambda N \\Delta t$ なので',
      ),
      eq('\\frac{dN}{dt} = -\\lambda N \\quad\\Longrightarrow\\quad N = N_0 e^{-\\lambda t}'),
      p('原子核の数が半分になるまでの時間を半減期 $T$ という。$N_0 e^{-\\lambda T} = N_0/2$ から'),
      eq(
        'N = N_0\\left(\\frac{1}{2}\\right)^{\\frac{t}{T}}, \\qquad \\lambda = \\frac{\\ln 2}{T} \\approx \\frac{0.693}{T}',
      ),
      p(
        '半減期は核種ごとに決まっていて、温度・圧力・化学的な状態では変わらない。$T$ 後に $1/2$、$2T$ 後に $1/4$、$3T$ 後に $1/8$ が残る。',
      ),
    ),
    section(
      '放射能',
      p(
        '単位時間あたりに崩壊する原子核の数を放射能 $A$ といい、単位はベクレル（Bq = 1/s）。放射能は残っている原子核の数に比例するので、放射能も同じ半減期で減っていく。',
      ),
      eq('A = -\\frac{dN}{dt} = \\lambda N = A_0\\left(\\frac{1}{2}\\right)^{\\frac{t}{T}}'),
    ),
    section(
      'グラフの読み方',
      ul(
        'N-t: シミュレーションで数えた残りの数（実線）と理論値（破線）。数が少ないほど、理論値からのずれ（統計的なゆらぎ）が目立つ',
        'ln N-t: 縦軸を $\\ln(N/N_0)$ にすると傾き $-\\lambda$ の直線になる（片対数グラフ）。指数関数的な減少かどうかはこのグラフで確かめる',
        'A-t: 直近 $T/10$ の間に崩壊した数から求めた放射能（測定値）と、理論値 $\\lambda N$',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '「$t$ が半減期の何倍か」を求めて $(1/2)^{t/T}$ を計算する。$t/T$ が整数でないときは指数の計算になる',
        '残っている割合が $1/8$ なら $3T$、$1/16$ なら $4T$ 経過したとわかる（年代測定）',
        '崩壊した数は $N_0 - N$。「残っている数」と「崩壊した数」を取り違えない',
        '1 個の原子核がいつ崩壊するかは予言できない。半減期は多数の原子核についての統計的な法則である',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '半減期 5 s の原子核 400 個は、15 s 後に何個残っているか。',
        p(
          '$15/5 = 3$ なので $400 \\times (1/2)^3 = 50$ 個。シミュレーションでは確率的にゆらぐので、ちょうど 50 個になるとは限らない。リセットして何回か確かめよう。',
        ),
      ),
      question(
        '残っている原子核の数が初めの 1/16 になるのは、半減期の何倍の時間がたったときか。',
        p('$(1/2)^4 = 1/16$ なので $4T$。「t = ○ T」の表示と残りの割合で確かめよう。'),
      ),
      question(
        '半減期 5 s の原子核が 400 個あるとき、最初の放射能はおよそ何 Bq か。',
        p(
          '$\\lambda = 0.693/5 \\approx 0.139$ /s なので $A_0 = \\lambda N_0 \\approx 55$ Bq。「この条件での値」と A-t グラフで確かめよう。',
        ),
      ),
      question(
        '初めの原子核の数を 100 個にすると、N-t グラフの理論値からのずれはどうなるか。',
        p(
          '割合で見たずれが大きくなる。ゆらぎの大きさはおよそ $\\sqrt{N}$ 程度なので、数が少ないほど相対的に大きい。半減期の法則は多数の原子核についての統計的な法則である。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '各原子核が崩壊する時刻を、平均 $1/\\lambda$ の指数分布に従う乱数で決めている。指数分布には「それまでの経過時間によらず、次の瞬間に崩壊する確率が一定」という性質（無記憶性）があり、これは崩壊定数 $\\lambda$ の定義そのものである。',
      ),
      p(
        '残りの数が $N_0(1/2)^{t/T}$ と統計誤差の範囲で一致すること、寿命の中央値が半減期・平均が $1/\\lambda$ に一致すること、放射能が $\\lambda N$ に一致することは自動テストで確認している。',
      ),
    ),
  );
}
