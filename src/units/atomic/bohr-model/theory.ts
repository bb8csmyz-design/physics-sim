import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      'ボーアの仮説',
      p(
        '原子核（電荷 $+Ze$）のまわりを電子（質量 $m$、電荷 $-e$）が半径 $r$、速さ $v$ で等速円運動しているとする。ボーアは次の 2 つの仮説を立てた。',
      ),
      ul(
        '量子条件: 電子は $mvr = n\\dfrac{h}{2\\pi}$（$n = 1, 2, 3, \\dots$）を満たす軌道だけを回り、そこでは光を出さない（定常状態）。$n$ を量子数という',
        "振動数条件: エネルギー $E_n$ の状態から $E_{n'}$ の状態に移るとき、差に等しいエネルギーの光子を放出（$E_n > E_{n'}$）または吸収（$E_n < E_{n'}$）する: $h\\nu = |E_n - E_{n'}|$",
      ),
      p(
        '量子条件は、電子の波（ド・ブロイ波長 $\\lambda = h/mv$）が軌道 1 周にちょうど $n$ 個入って定常波になる条件 $2\\pi r = n\\lambda$ と同じである。',
      ),
    ),
    section(
      '軌道半径とエネルギー準位',
      p('静電気力が向心力になるので、運動方程式は'),
      eq('m\\frac{v^2}{r} = k\\frac{Ze^2}{r^2}'),
      p('これと量子条件から $v$ を消去すると'),
      eq(
        'r_n = \\frac{h^2}{4\\pi^2 k m Z e^2}\\,n^2 = \\frac{\\varepsilon_0 h^2}{\\pi m Z e^2}\\,n^2 \\qquad (r_1 = 5.3\\times10^{-11}\\ \\text{m: ボーア半径})',
      ),
      p('電子のエネルギーは運動エネルギーと静電気力による位置エネルギー（無限遠が基準）の和で'),
      eq(
        'E_n = \\frac{1}{2}mv^2 - k\\frac{Ze^2}{r_n} = -\\frac{kZe^2}{2r_n} = -\\frac{2\\pi^2k^2me^4 Z^2}{h^2}\\cdot\\frac{1}{n^2} \\approx -\\frac{13.6\\,Z^2}{n^2}\\ \\text{eV}',
      ),
      p(
        'エネルギーはとびとびの値（エネルギー準位）しかとれない。$n = 1$ が最もエネルギーの低い基底状態で、$n \\geq 2$ を励起状態という。$E = 0$ は電子が原子核から離れた状態（電離）で、水素原子のイオン化エネルギーは 13.6 eV である。',
      ),
    ),
    section(
      '光の波長とスペクトル系列',
      p("振動数条件 $h\\nu = hc/\\lambda = E_n - E_{n'}$ に $E_n$ を代入すると"),
      eq(
        "\\frac{1}{\\lambda} = RZ^2\\left(\\frac{1}{n'^2} - \\frac{1}{n^2}\\right), \\qquad R = \\frac{2\\pi^2k^2me^4}{ch^3} = 1.10\\times10^{7}\\ /\\text{m}",
      ),
      p(
        "これは実験で見つかっていた水素のスペクトルの規則（リュードベリの式）と一致し、$R$（リュードベリ定数）の値も物理定数から正しく導かれる。移った後の準位 $n'$ で分類した線の集まりを系列という。",
      ),
      ul(
        "ライマン系列（$n' = 1$）: 紫外線。最も短い波長（系列の極限）は 91 nm",
        "バルマー系列（$n' = 2$）: $n = 3, 4, 5, 6$ からの線は可視光（656 nm の赤い線が $\\text{H}_\\alpha$ 線）。系列の極限は 365 nm",
        "パッシェン系列（$n' = 3$）: 赤外線",
      ),
    ),
    section(
      'グラフと図の読み方',
      ul(
        '左の図は軌道を実際の縮尺で描いている（$r \\propto n^2$）。電子の回る速さは見やすく遅くしてあるが、内側と外側の比（角速度 $\\propto 1/n^3$）は実際のとおり',
        '右の準位図は縦軸が等間隔の eV 目盛り。$n$ が大きいほど間隔が狭く、$E = 0$ に近づく',
        '下のスペクトルは $n \\leq 7$ のすべての遷移の線。選んだ遷移の線を太く、可視光の範囲を色の帯で示している',
        '「1/λ-1/n²」のグラフ: 同じ系列の線は、$1/\\lambda$ を $1/n^2$ に対してとると傾き $-RZ^2$ の直線に乗る。縦軸の切片が系列の極限',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '$r_n \\propto n^2$、$v_n \\propto 1/n$、$E_n \\propto -1/n^2$。原子番号 $Z$ の水素様イオンでは $r \\propto 1/Z$、$E \\propto Z^2$',
        '$E_n$ の式の導出（運動方程式 + 量子条件 → $r_n$ → $E_n$）がそのまま問われる。運動エネルギー $K = -E_n$、位置エネルギー $U = 2E_n$ の関係も使える',
        '光子のエネルギー $h\\nu$ と波長: $\\lambda\\,[\\text{nm}] \\approx 1240 / h\\nu\\,[\\text{eV}]$',
        '吸収されるのは準位の差にちょうど等しいエネルギーの光子だけ（同じ 2 準位なら吸収と放出の波長は同じ）',
        'ある系列で最も長い波長は隣の準位からの遷移、最も短い波長は $n \\to \\infty$（系列の極限）',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '水素原子で $n = 3$ から $n = 2$ に移るときに出る光の波長は？',
        p(
          '$h\\nu = 13.6(1/4 - 1/9) \\approx 1.89$ eV なので $\\lambda \\approx 1240/1.89 \\approx 656$ nm（赤い光、$\\text{H}_\\alpha$ 線）。初期値のまま確かめよう。',
        ),
      ),
      question(
        '基底状態の水素原子が吸収できる光の波長のうち、最も長いものは？',
        p(
          '$n = 1 \\to 2$ の 10.2 eV なので約 122 nm（紫外線）。「初めの準位」を 1、「移った後の準位」を 2 にして確かめよう。これより低いエネルギーの光子は吸収されない。',
        ),
      ),
      question(
        'He⁺（$Z = 2$）で $n = 4 \\to 3$ の光の波長は、水素原子の同じ遷移と比べてどうなるか。',
        p(
          'エネルギー差が $Z^2 = 4$ 倍になるので、波長は $1/4$ 倍（1875 nm → 469 nm）。原子番号を変えて確かめよう。',
        ),
      ),
      question(
        '量子数 $n$ が 2 倍になると、軌道半径・速さ・1 周の時間はそれぞれ何倍か。',
        p(
          '$r \\propto n^2$ で 4 倍、$v \\propto 1/n$ で 1/2 倍、周期 $T = 2\\pi r/v \\propto n^3$ で 8 倍。「この条件での値」と左の図で確かめよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        'ボーア模型では電子の運動は等速円運動なので、数値積分せずに式で位置を求めている。実際の 1 周の時間は $10^{-16}$ s 程度なので、アニメーションの時間は模式的なものである。準位を移る瞬間（$t = 2$ s）に光子を放出・吸収する。',
      ),
      p(
        '量子条件・運動方程式・エネルギー保存（光子のエネルギー = 準位の差）、ボーア半径・13.6 eV・リュードベリ定数の値、水素のバルマー系列の実測波長（656.3, 486.1, 434.0, 410.2 nm）との一致は自動テストで確認している。',
      ),
    ),
  );
}
