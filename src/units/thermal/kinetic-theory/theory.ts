import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '分子が壁に与える力積',
      p(
        '一辺 $L$ の立方体の容器に、質量 $m$ の分子が $N$ 個入っている。$x$ 軸に垂直な壁（$x = L$）に、速度の $x$ 成分が $v_x$ の分子が弾性衝突すると、$v_x$ は $-v_x$ になる。分子の運動量の変化は $-2mv_x$ なので、壁は分子から力積 $2mv_x$ を受ける。',
      ),
      p(
        'この分子は容器を往復して $2L/v_x$ ごとに同じ壁に当たる。時間 $t$ の間に $\\dfrac{v_x t}{2L}$ 回当たるので、壁が受ける平均の力は',
      ),
      eq('f = 2mv_x \\times \\frac{v_x t}{2L} \\div t = \\frac{mv_x^{\\,2}}{L}'),
    ),
    section(
      '圧力の式',
      p(
        '$N$ 個の分子についての和をとり、$v_x^{\\,2}$ の平均を $\\langle v_x^{\\,2} \\rangle$ とすると、壁が受ける力は $F = \\dfrac{Nm\\langle v_x^{\\,2}\\rangle}{L}$。分子の運動はどの向きにもかたよらないので $\\langle v_x^{\\,2}\\rangle = \\langle v_y^{\\,2}\\rangle = \\langle v_z^{\\,2}\\rangle = \\frac{1}{3}\\langle v^2\\rangle$。圧力は $p = F/L^2$、体積は $V = L^3$ だから',
      ),
      eq('p = \\frac{Nm\\langle v^2 \\rangle}{3V}'),
    ),
    section(
      '温度と分子の運動エネルギー',
      p(
        '上の式を状態方程式 $pV = nRT$（$n = N/N_\\mathrm{A}$）と比べると、分子 1 個の平均運動エネルギーは絶対温度に比例することがわかる。',
      ),
      eq(
        '\\frac{1}{2}m\\langle v^2 \\rangle = \\frac{3}{2}\\frac{R}{N_\\mathrm{A}}T = \\frac{3}{2}kT, \\qquad k = \\frac{R}{N_\\mathrm{A}} \\approx 1.38\\times10^{-23}\\ \\mathrm{J/K}',
      ),
      p('$k$ をボルツマン定数という。二乗平均速度と、単原子分子の理想気体の内部エネルギーは'),
      eq(
        '\\sqrt{\\langle v^2 \\rangle} = \\sqrt{\\frac{3kT}{m}} = \\sqrt{\\frac{3RT}{M}}, \\qquad U = N\\cdot\\frac{3}{2}kT = \\frac{3}{2}nRT',
      ),
      p('$M$ はモル質量 [kg/mol]（1 g/mol = 1×10⁻³ kg/mol）。'),
    ),
    section(
      'グラフと数値の読み方',
      ul(
        '圧力のグラフの「直近」は、分子が容器を横切る時間 $L/\\sqrt{\\langle v^2\\rangle}$ の間に壁が受けた力積から求めた圧力。分子がいつ当たるかで大きくゆらぐ',
        '「平均」（$t = 0$ からの時間平均）は時間とともにゆらぎが小さくなり、状態方程式による値 $NkT/V$（破線）に近づく。「状態方程式との比 $pV/(NkT)$」が 1 に近づくことを確かめよう',
        '分子数 $N$ を減らすと、直近の値のゆらぎが大きくなる。たくさんの分子の衝突を平均したものが圧力である',
        'このシミュレーションの分子は数百個しかないので、圧力は $10^{-16}$ Pa 程度ととても小さい。実際の気体は 1 mol で $6.0\\times10^{23}$ 個の分子を含むので、同じ式で $10^{5}$ Pa 程度（大気圧）になる',
        'ヒストグラムは分子の速さの分布。曲線は理論的な分布（マクスウェル分布）で、温度を上げると速い分子が増えて分布が右に広がる',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '導出の流れ「1 回の力積 $2mv_x$ → 衝突の間隔 $2L/v_x$ → 平均の力 $mv_x^{\\,2}/L$ → $\\langle v_x^{\\,2}\\rangle = \\frac{1}{3}\\langle v^2\\rangle$ → $p = \\frac{Nm\\langle v^2\\rangle}{3V}$」を自分で再現できるようにする',
        '同じ温度なら、分子の種類によらず平均運動エネルギー $\\frac{3}{2}kT$ は等しい。二乗平均速度は $\\sqrt{M}$ に反比例する',
        '分子の質量は $m = M/N_\\mathrm{A}$。$M$ を g/mol のまま代入しないよう単位に注意する',
        '内部エネルギー $U = \\frac{3}{2}nRT$ は単原子分子の場合。温度だけで決まり、体積にはよらない',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '体積を変えずに絶対温度を 4 倍にすると、二乗平均速度と圧力はそれぞれ何倍になるか。',
        p(
          '$\\sqrt{\\langle v^2\\rangle} \\propto \\sqrt{T}$ なので 2 倍、$p \\propto T$ なので 4 倍。$T$ を 250 K → 1000 K にして、ヒストグラムの $\\sqrt{\\langle v^2\\rangle}$ と測った圧力を比べよう。',
        ),
      ),
      question(
        '同じ温度の He（4 g/mol）と Ar（40 g/mol）では、二乗平均速度は何倍ちがうか。平均運動エネルギーはどうか。',
        p(
          '$\\sqrt{\\langle v^2\\rangle} \\propto 1/\\sqrt{M}$ なので He は Ar の $\\sqrt{10} \\approx 3.2$ 倍速い。平均運動エネルギー $\\frac{3}{2}kT$ は等しい。「この条件での値」で確かめよう。',
        ),
      ),
      question(
        '容器の一辺 $L$ を 2 倍にすると、圧力は何倍になるか。1 個の分子が同じ壁に当たる間隔はどうなるか。',
        p(
          '体積は 8 倍になるので、圧力は $1/8$ 倍。衝突の間隔 $2L/v_x$ は 2 倍、壁の面積は 4 倍になり、$1/2 \\times 1/4 = 1/8$ と考えてもよい。',
        ),
      ),
      question(
        '300 K の He の二乗平均速度は約何 m/s か（$R = 8.31$ J/(mol·K)）。',
        p(
          '$\\sqrt{3RT/M} = \\sqrt{3 \\times 8.31 \\times 300 / (4\\times10^{-3})} \\approx 1.37\\times10^3$ m/s。音速（約 340 m/s）よりずっと速い。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '分子どうしの衝突は無視し（理想気体）、壁との弾性衝突は「壁で折り返す」計算で厳密に求めている。1 ステップの間に何回壁に当たっても、衝突の回数と力積を正しく数える。速度は乱数でマクスウェル分布から選び、平均運動エネルギーがちょうど $\\frac{3}{2}kT$ になるようにそろえている。分子は速いので、時間を 1 万分の 1 の速さに遅くして表示している。測った圧力が $p = Nm\\langle v^2\\rangle/(3V)$ と状態方程式に一致すること、速さの分布がマクスウェル分布に合うことは自動テストで確認している。',
      ),
    ),
  );
}
