import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '屈折の法則',
      p(
        '光が屈折率 $n_1$ の媒質から $n_2$ の媒質へ進むとき、入射角 $\\theta_1$ と屈折角 $\\theta_2$（どちらも法線から測る）の間に次の関係がある。',
      ),
      eq(
        'n_1 \\sin\\theta_1 = n_2 \\sin\\theta_2, \\qquad \\frac{\\sin\\theta_1}{\\sin\\theta_2} = \\frac{n_2}{n_1} = n_{12} = \\frac{v_1}{v_2} = \\frac{\\lambda_1}{\\lambda_2}',
      ),
      p(
        '屈折率 $n$ の媒質中で、光の速さは $c/n$、波長は $\\lambda_0/n$ になる（$\\lambda_0$ は真空中の波長）。振動数は媒質によらず変わらない。',
      ),
    ),
    section(
      '波面で見る屈折（ホイヘンスの原理）',
      p(
        '画面の濃淡は光の電場（波の山が濃い）を表す。屈折率の大きい媒質では波長が短くなり、波面（山の列）の間隔が詰まる。境界面に沿って波の山がとぎれずにつながるためには、境界面に沿った山の間隔 $\\lambda_1/\\sin\\theta_1$ と $\\lambda_2/\\sin\\theta_2$ が等しくなければならない。これを書きかえたものが屈折の法則である。',
      ),
    ),
    section(
      '全反射',
      p(
        '屈折率の大きい媒質から小さい媒質へ進むとき（$n_1 > n_2$）、入射角を大きくすると屈折角が先に 90° に達する。このときの入射角を臨界角 $\\theta_{\\mathrm{c}}$ という。',
      ),
      eq('\\sin\\theta_{\\mathrm{c}} = \\frac{n_2}{n_1}'),
      p(
        '入射角が臨界角を超えると屈折光はなくなり、光はすべて反射される（全反射）。媒質 2 側には境界面のすぐ近くにだけしみ出す波（エバネッセント波）ができ、奥へ行くほど急に弱まる。$n_1 = 1.50$、$n_2 = 1.00$ にして入射角を動かし、確かめよう。',
      ),
    ),
    section(
      '数値の読み方',
      ul(
        '「屈折角」が「全反射」になる境目が「臨界角」の値と一致する',
        '「反射率」は入射光のエネルギーのうち反射される割合（発展）。空気とガラスの境界に垂直に入射すると約 4%。全反射では 100%',
        '反射光の矢印は反射率が小さいとき細い破線で描いている',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '角度は境界面ではなく法線から測る',
        '$n_1\\sin\\theta_1 = n_2\\sin\\theta_2$ は何枚の層を通っても順に使える（平行な層なら $n\\sin\\theta$ は一定）',
        '全反射は「屈折率の大きい側から小さい側へ」のときだけ起こる。光ファイバー、水中から見た空（スネルの窓）などに応用される',
        '水中の物体が浅く見える（見かけの深さ $h/n$）のも屈折による',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '空気（1.00）からガラス（1.50）へ 40° で入射した光の屈折角は？',
        p(
          '$\\sin\\theta_2 = \\sin 40^\\circ / 1.50 \\approx 0.429$ より $\\theta_2 \\approx 25.4^\\circ$。既定の条件で確かめよう。',
        ),
      ),
      question(
        '水（1.33）から空気へ出る光の臨界角は？',
        p(
          '$\\sin\\theta_{\\mathrm{c}} = 1/1.33$ より約 48.8°。$n_1 = 1.33$、$n_2 = 1.00$ にして、入射角 48° と 49° で屈折光があるかを見比べよう。',
        ),
      ),
      question(
        '媒質 2 に入ると、光の振動数・速さ・波長はそれぞれ何倍になるか。',
        p('振動数は変わらず、速さと波長は $n_1/n_2$ 倍。数値の欄で確かめよう。'),
      ),
    ),
    section(
      '数値計算について',
      p(
        '光を平面波として扱い、入射波・反射波・屈折波の電場を解析的に足し合わせて描いている（電場が紙面に垂直な偏光）。自動テストでは、境界面の上下で電場とその傾きがつながること（ここから屈折の法則が出る）、反射率と透過率の和が 1 になること（エネルギー保存）、光学距離が最小になる道すじ（フェルマーの原理）を数値的に探すと屈折の法則を満たすことを、パラメータ範囲の全隅で確かめている。光の振動は非常に速いので、時刻は周期 $T$ を単位にしてゆっくり表示している。',
      ),
    ),
  );
}
