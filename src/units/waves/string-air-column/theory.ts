import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '定常波のでき方',
      p(
        '弦や管の端で反射した波（反射波）と、もとの波（入射波）が重なると、波形が左右に進まず、その場で振動するだけの波ができる。これを定常波という。',
      ),
      eq(
        '\\frac{A}{2}\\sin(kx - \\omega t) + \\frac{A}{2}\\sin(kx + \\omega t) = A\\sin kx \\cos\\omega t',
      ),
      p(
        'まったく振動しない点を節、最も大きく振動する点を腹という。節どうし（腹どうし）の間隔は $\\lambda/2$、節と腹の間隔は $\\lambda/4$。「入射波と反射波」をオンにして、2 つの進行波の和が定常波になることを確かめよう。',
      ),
    ),
    section(
      '弦の固有振動（両端固定）',
      p('両端が節になる定常波だけが続く。長さ $L$ に半波長 $\\lambda/2$ が $n$ 個入るので'),
      eq(
        'L = n\\cdot\\frac{\\lambda}{2}, \\qquad f_n = \\frac{v}{\\lambda} = \\frac{n v}{2L} \\quad (n = 1, 2, 3, \\dots)',
      ),
      p(
        '弦を伝わる波の速さは張力 $S$ と線密度 $\\rho$ で決まり $v = \\sqrt{S/\\rho}$。$n=1$ を基本振動、$n = 2, 3, \\dots$ を 2 倍振動、3 倍振動という。',
      ),
    ),
    section(
      '気柱の固有振動',
      p(
        '管の中の空気の振動（縦波）でも定常波ができる。閉じた端（閉口端）は空気が動けないので変位の節、開いた端（開口端）は変位の腹になる。',
      ),
      eq(
        '\\begin{aligned} \\text{開管}&: \\ f_n = \\frac{nV}{2L} \\quad (n = 1, 2, 3, \\dots) \\\\ \\text{閉管}&: \\ f = \\frac{(2n-1)V}{4L} \\quad (\\text{基本振動の奇数倍だけ}) \\end{aligned}',
      ),
      p(
        '実際の腹は管口より少し外側にでき、そのずれ $\\Delta x$ を開口端補正という。$L$ を $L + \\Delta x$（開管では $L + 2\\Delta x$）に置き換えればよい。',
      ),
    ),
    section(
      '空気の疎密と圧力',
      p(
        '縦波では、隣り合う空気が近づくところが密、離れるところが疎になる。「空気の疎密」をオンにすると、変位の節の位置で空気が最も激しく密になったり疎になったりし、変位の腹では密度がほとんど変わらないことが分かる。',
      ),
      ul(
        '閉口端（変位の節）は密度変化・圧力変化が最大',
        '開口端（変位の腹）は外の空気とつながっているので、密度変化・圧力変化が 0',
      ),
    ),
    section(
      'グラフと数値の読み方',
      ul(
        '「観測点の変位」のグラフ: 観測点が節なら振幅 0、腹なら最大。観測点を動かして確かめよう',
        '「この条件での値」に固有振動数・波長・節と腹の数を表示している。閉管では「振動の番号 $n$」を 1 増やすと、振動数は基本振動の 2 倍ずつ増える（1, 3, 5, … 倍）',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        'まず端が節か腹かを決め、図をかいて $L$ に $\\lambda/4$ がいくつ入るかを数える',
        '閉管は奇数倍振動だけ。同じ長さなら閉管の基本振動数は開管の半分',
        '気柱共鳴の実験で、共鳴する管の長さ $L_1, L_2$ の差は半波長: $\\lambda = 2(L_2 - L_1)$、開口端補正は $\\Delta x = \\lambda/4 - L_1$',
        '「密度変化が最大」は変位の節、「最も大きく振動」は変位の腹',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '長さ 0.60 m の閉管（開口端補正 0、音速 340 m/s）の基本振動数と、その次に共鳴する振動数は？',
        p(
          '$f_1 = \\dfrac{340}{4\\times 0.60} \\approx 142$ Hz、次は 3 倍振動で約 425 Hz。閉管を選んで $n = 1, 2$ で確かめよう。',
        ),
      ),
      question(
        '開管の 3 倍振動では、管の中に節がいくつあるか。',
        p('両端が腹で、半波長が 3 つ入るので節は 3 つ。「節と腹の位置」で確かめよう。'),
      ),
      question(
        '開口端補正 $\\Delta x = 0.02$ m を入れると、閉管の基本振動数は何 % 変わるか（$L = 0.60$ m）。',
        p('$f \\propto 1/(L + \\Delta x)$ なので $0.60/0.62 \\approx 0.968$ 倍、約 3 % 下がる。'),
      ),
    ),
    section(
      '数値計算について',
      p(
        '画面の定常波は、端の条件を満たす解析解 $y = Y(x)\\cos\\omega t$ をそのまま描いている。公式とは別に、波動方程式 $\\partial^2 y/\\partial t^2 = v^2\\,\\partial^2 y/\\partial x^2$ を差分法と速度ベルレ法で時間発展させ、測った振動数が固有振動数の公式と一致する（格子を細かくすると 2 次で収束する）ことを自動テストで確認している。音は速いので、1 秒間に約 1 回振動して見えるスロー再生にしている。',
      ),
    ),
  );
}
