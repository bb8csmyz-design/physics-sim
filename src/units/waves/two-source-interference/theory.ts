import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '重ね合わせと経路差',
      p(
        '2 つの波源 $\\mathrm{S_1}$, $\\mathrm{S_2}$ から同じ振幅・振動数の波が出ている。点 P の変位は、それぞれの波の変位の和になる（重ね合わせの原理）。2 つの波が P に届くまでの距離の差',
      ),
      eq('\\Delta = |\\mathrm{S_1P} - \\mathrm{S_2P}|'),
      p(
        'を経路差という。経路差が波長の何倍かで、P で 2 つの波の山と山がそろうか、山と谷が重なるかが決まる。',
      ),
    ),
    section(
      '強め合う条件・弱め合う条件',
      p('2 つの波源が同位相で振動するとき（$m = 0, 1, 2, \\dots$）'),
      eq(
        '\\begin{aligned} \\text{強め合う}&: \\ \\Delta = m\\lambda \\\\ \\text{弱め合う}&: \\ \\Delta = \\left(m + \\tfrac{1}{2}\\right)\\lambda \\end{aligned}',
      ),
      p(
        '逆位相のときは条件が入れかわる。合成波の振幅は $2A\\left|\\cos\\left(\\dfrac{\\pi\\Delta}{\\lambda} - \\dfrac{\\varphi}{2}\\right)\\right|$（$\\varphi$ は波源の位相差）で、強め合う点では $2A$、弱め合う点では $0$ になる。',
      ),
    ),
    section(
      '強め合う線・弱め合う線',
      p(
        '経路差が一定の点を結ぶと、$\\mathrm{S_1}$, $\\mathrm{S_2}$ を焦点とする双曲線になる。強め合う点を結んだ線（腹線）は水面が大きく揺れ、弱め合う点を結んだ線（節線）はほとんど揺れない。',
      ),
      p(
        '線分 $\\mathrm{S_1S_2}$ 上では経路差が $|2x|$ なので、腹線・節線は $\\lambda/2$ 間隔で並ぶ（定常波と同じ）。線分と交わる線の本数は、$|m\\lambda| < d$ や $|(m+\\frac{1}{2})\\lambda| < d$ を満たす整数 $m$ の個数で求まる。',
      ),
    ),
    section(
      'グラフと数値の読み方',
      ul(
        '水面の濃淡: 濃い部分が山、背景色の部分が谷。腹線に沿って山と谷が外へ進み、節線の上はいつも中間の色のまま',
        '「点 P の変位」のグラフ: $\\mathrm{S_1}$ からの波と $\\mathrm{S_2}$ からの波（破線）と、その和（実線）。経路差が $m\\lambda$ なら 2 つの破線がそろい、$(m+\\frac{1}{2})\\lambda$ なら打ち消し合う',
        '「経路差 / 波長」が整数なら強め合い、整数 + 0.5 なら弱め合う（同位相のとき）',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '経路差を「波長の何倍か」で表してから判定する。$\\Delta/\\lambda$ が整数か半整数か',
        '線分 $\\mathrm{S_1S_2}$ 上の節（腹）の数を問われたら、$-d < \\Delta < d$ の範囲で条件を満たす $m$ を数える。波源の位置そのものは数えない',
        '波源が逆位相なら条件が入れかわる。垂直二等分線は同位相なら腹線、逆位相なら節線',
        '遠方では腹線の方向が $d\\sin\\theta = m\\lambda$ を満たす（ヤングの実験と同じ式）',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$d = 6$ cm、$\\lambda = 2$ cm、同位相のとき、線分 $\\mathrm{S_1S_2}$ と交わる節線は何本か。',
        p(
          '$|(m+\\frac{1}{2})\\times 2| < 6$ を満たす $m$ は $-3, -2, -1, 0, 1, 2$ の 6 本。「この条件での値」と「弱め合う線」の表示で確かめよう。強め合う線は $|2m| < 6$ より 5 本。',
        ),
      ),
      question(
        '点 P を $\\mathrm{S_1}$ から 10 cm、$\\mathrm{S_2}$ から 7 cm の位置に置いた。$\\lambda = 2$ cm、同位相のとき P はどうなるか。',
        p(
          '経路差 3 cm $= 1.5\\lambda$ なので弱め合い、P はほとんど振動しない。逆位相に切りかえると強め合う。',
        ),
      ),
      question(
        '波長を短くすると、腹線の本数と間隔はどう変わるか。',
        p(
          '$d/\\lambda$ が大きくなるので本数が増え、線どうしの間隔はせまくなる。スライダーで確かめよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '各波源からの波 $A\\sin(\\omega t - kr)$ を足し合わせた解析解を、そのまま毎時刻計算して描いている（距離による振幅の減衰は無視）。時間発展させて測った点 P の振幅が干渉の式と一致すること、線分 $\\mathrm{S_1S_2}$ 上で数値的に数えた腹・節の数が公式と一致することを、パラメータ範囲の全隅について自動テストしている。振動数は 5 Hz で、画面は 1/5 倍のスロー再生。',
      ),
    ),
  );
}
