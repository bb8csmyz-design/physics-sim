import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      'ヤングの実験',
      p(
        '1 つのスリットを通った光を、間隔 $d$ の 2 つのスリット $\\mathrm{S_1}$, $\\mathrm{S_2}$ に当てると、2 つのスリットからは同位相の光が出る（ホイヘンスの原理）。距離 $L$ のスクリーン上の点 P では、2 つの光の経路差で明るさが決まる。',
      ),
      eq(
        '\\Delta = |\\mathrm{S_2P} - \\mathrm{S_1P}| \\approx d\\sin\\theta \\approx \\frac{d x}{L}',
      ),
      p('経路差が波長の整数倍なら明線、半整数倍なら暗線になる（$m = 0, 1, 2, \\dots$）。'),
      eq(
        '\\text{明線}: \\ \\frac{dx}{L} = m\\lambda, \\quad x_m = \\frac{mL\\lambda}{d}, \\qquad \\text{明線の間隔}: \\ \\Delta x = \\frac{L\\lambda}{d}',
      ),
    ),
    section(
      '回折格子',
      p(
        '多数のスリットが等間隔 $d$（格子定数）で並んだものを回折格子という。隣り合うスリットからの光の経路差が $d\\sin\\theta$ なので、すべての光が強め合う方向は',
      ),
      eq('d\\sin\\theta_m = m\\lambda \\quad (m = 0, \\pm 1, \\pm 2, \\dots)'),
      p(
        '$|\\sin\\theta| < 1$ なので、現れる明線の次数は $|m| < d/\\lambda$ に限られる。スリットの数 $N$ を増やすと、明線の位置は変わらずに幅が細く鋭くなり、明線の間はほとんど暗くなる（主極大の間に暗点が $N - 1$ 個できる）。回折格子は角度が大きいので、位置は $x_m = L\\tan\\theta_m$ で求める。',
      ),
    ),
    section(
      '媒質の中での実験',
      p(
        '装置全体を屈折率 $n$ の液体に入れると、光の波長は $\\lambda/n$ に短くなる。明線の間隔も $1/n$ 倍になる。「装置を満たす媒質の屈折率」を 1.33（水）にして確かめよう。',
      ),
    ),
    section(
      '画面と数値の読み方',
      ul(
        '左は模式図。実際には $\\lambda \\ll d \\ll L$ なので、波長を大きく誇張して描いている',
        '右はスクリーン上の明暗（光の色で表示）と光の強さのグラフで、縦軸は実寸。$m$ は明線の次数',
        '波長を長く（赤く）すると明線の間隔が広がり、スリットの間隔を広げると狭くなる',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        'ヤングの実験は $\\theta$ が小さい近似 $\\sin\\theta \\approx \\tan\\theta \\approx x/L$ を使う。$\\Delta x = L\\lambda/d$ はそのまま覚えて使えるようにする',
        '回折格子では角度が大きいので近似は使えない。$d\\sin\\theta = m\\lambda$ と $x = L\\tan\\theta$ を分けて使う',
        '「1 mm あたり $N$ 本」の格子の格子定数は $d = 1/N$ mm',
        '白色光では、中央（$m = 0$）は白、それ以外は波長の短い紫側が内側に並ぶ虹色になる',
        '一方のスリットの前に薄膜（厚さ $t$、屈折率 $n$）を置くと、光路差が $(n-1)t$ 増えて縞全体がずれる',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '$\\lambda = 600$ nm、$d = 0.50$ mm、$L = 2.0$ m のとき、明線の間隔は？',
        p(
          '$\\Delta x = \\dfrac{2.0\\times 600\\times 10^{-9}}{0.50\\times 10^{-3}} = 2.4\\times 10^{-3}$ m = 2.4 mm。既定の条件で確かめよう。',
        ),
      ),
      question(
        '1 mm あたり 500 本の回折格子に波長 600 nm の光を当てた。1 次の明線の回折角と、見える明線の数は？',
        p(
          '$d = 2.0\\ \\mu$m、$\\sin\\theta_1 = 0.30$ より $\\theta_1 \\approx 17.5^\\circ$。$|m| < d/\\lambda = 3.3$ なので $m = 0, \\pm1, \\pm2, \\pm3$ の 7 本。',
        ),
      ),
      question(
        'ヤングの実験で、赤い光（700 nm）と青い光（450 nm）では、どちらの明線の間隔が広いか。',
        p(
          '$\\Delta x \\propto \\lambda$ なので赤い光のほうが広い（約 1.6 倍）。波長のスライダーで確かめよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        'スクリーン上の光の強さは、遠方での公式 $I = \\left[\\dfrac{\\sin(N\\varphi/2)}{N\\sin(\\varphi/2)}\\right]^2$（$\\varphi = 2\\pi d\\sin\\theta/\\lambda$）で描いている（スリットの幅による回折は無視）。自動テストでは、各スリットからの光の電場をスクリーン上の点までの実際の距離で足し合わせて時間平均し、数値的に探した明線の位置が $x_m = mL\\lambda/d$ や $d\\sin\\theta_m = m\\lambda$ と一致することを、パラメータ範囲の全隅で確かめている。',
      ),
    ),
  );
}
