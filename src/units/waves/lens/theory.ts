import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      '作図の 3 本の光線',
      p('物体の先端から出る光のうち、次の 3 本は進み方がすぐ分かる。'),
      ul(
        '① 光軸に平行に入る光線 → 凸レンズでは向こう側の焦点を通る（凹レンズでは手前の焦点から出たように広がる）',
        '② レンズの中心を通る光線 → そのまま直進する',
        '③ 手前の焦点を通って入る光線（凹レンズでは向こう側の焦点に向かう光線）→ 光軸に平行に出る',
      ),
      p(
        '出た光線が実際に 1 点に集まれば実像、出た光線を逆に延長した線が 1 点に集まれば虚像ができる。「作図の光線」で確かめよう（虚像のときの延長線は破線）。',
      ),
    ),
    section(
      'レンズの式と倍率',
      eq('\\frac{1}{a} + \\frac{1}{b} = \\frac{1}{f}, \\qquad m = \\left|\\frac{b}{a}\\right|'),
      p(
        '$a$ はレンズから物体まで、$b$ はレンズから像までの距離、$f$ は焦点距離。符号の約束: 凸レンズは $f > 0$、凹レンズは $f < 0$。$b > 0$ ならレンズの後ろ（右）に実像（倒立）、$b < 0$ なら物体と同じ側に虚像（正立）。',
      ),
    ),
    section(
      '物体を近づけると像はどう動くか（凸レンズ）',
      ul(
        '$a > 2f$: 縮小された倒立の実像が $f < b < 2f$ にできる',
        '$a = 2f$: 等倍の倒立の実像が $b = 2f$ にできる',
        '$f < a < 2f$: 拡大された倒立の実像が $b > 2f$ にできる。$a \\to f$ で像は無限遠へ',
        '$a = f$: 光は平行に出て像はできない',
        '$a < f$: 拡大された正立の虚像（虫めがね）',
      ),
      p(
        '「像の位置」のグラフで、物体が焦点を通り過ぎるとき $b$ が $+\\infty$ から $-\\infty$ へ飛ぶことを確かめよう。凹レンズでは、物体がどこにあっても縮小された正立の虚像になる。',
      ),
    ),
    section(
      'グラフと数値の読み方',
      ul(
        '「位置」のグラフ: 物体の位置 $a$ と像の位置 $b$。像は物体と同じ向きに動く（物体が近づくと実像は遠ざかる）',
        '「高さ」のグラフ: 像の高さ（上向き正）。負なら倒立',
        '像の速さは $|db/dt| = m^2 |da/dt|$。$m > 1$ のとき像は物体より速く動く',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        'まず $1/a + 1/b = 1/f$ で $b$ を求め、符号で実像か虚像かを判定してから倍率 $|b/a|$ を計算する',
        '凹レンズは $f$ を負にして同じ式を使う。像は必ず虚像（$b < 0$）',
        '作図問題では 3 本のうち 2 本で像が決まる。レンズの端を通る光線が実際にはなくても作図には使える',
        'レンズの式は光軸に近い光線（近軸光線）についての近似。物体が光軸から離れすぎると収差でずれる',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '焦点距離 10 cm の凸レンズの前方 30 cm に物体を置いた。像の位置と倍率は？',
        p(
          '$1/30 + 1/b = 1/10$ より $b = 15$ cm、倍率 $15/30 = 0.5$。倒立の実像。$a_0 = 0.30$ m、速さ 0 にして確かめよう。',
        ),
      ),
      question(
        '同じレンズで、物体を 5 cm の位置に置くと？',
        p('$1/5 + 1/b = 1/10$ より $b = -10$ cm。物体と同じ側に、2 倍の正立の虚像ができる。'),
      ),
      question(
        '焦点距離 10 cm の凹レンズの前方 10 cm に物体を置いた。像は？',
        p(
          '$1/10 + 1/b = -1/10$ より $b = -5$ cm。0.5 倍の正立の虚像。凹レンズに切りかえて確かめよう。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '物体は等速で動くので位置は解析解 $a = a_0 - vt$ で求め、像はレンズの式から計算している。自動テストでは、薄いレンズの規則で多数の光線を追跡すると全てレンズの式の像に集まること、さらに球面でできた実際のレンズを屈折の法則で厳密に光線追跡しても（近軸光線なら）レンズの式どおりの点に集まることを、パラメータ範囲の全隅で確かめている。',
      ),
    ),
  );
}
