import { eq, note, p, question, section, theory, ul } from '@/ui/theory';

export function buildTheory(): HTMLElement {
  return theory(
    section(
      'ドップラー効果の公式',
      p(
        '音源（振動数 $f_0$）と観測者が一直線上を動くとき、観測者が聞く音の振動数 $f$ は、音源から観測者へ向かう向きを正として',
      ),
      eq('f = \\frac{V - v_{\\mathrm{O}}}{V - v_{\\mathrm{S}}}\\, f_0'),
      p(
        '$V$ は音速、$v_{\\mathrm{S}}$ は音源の速度、$v_{\\mathrm{O}}$ は観測者の速度。音源が観測者に近づく（$v_{\\mathrm{S}}>0$）と分母が小さくなり $f$ は高くなる。観測者が音源から遠ざかる（$v_{\\mathrm{O}}>0$）と分子が小さくなり $f$ は低くなる。',
      ),
    ),
    section(
      '音源が動くと波長が変わる',
      p(
        '音源は 1 秒間に $f_0$ 枚の波面を出す。音は空気に対して速さ $V$ で進むので、1 秒後に前方の $V - v_{\\mathrm{S}}$ の区間に $f_0$ 個の波が詰まる。よって音源の前方の波長は',
      ),
      eq(
        '\\lambda_1 = \\frac{V - v_{\\mathrm{S}}}{f_0}, \\qquad \\lambda_2 = \\frac{V + v_{\\mathrm{S}}}{f_0}\\ (\\text{後方})',
      ),
      p(
        '「波長 λ の表示」をオンにして、音源の前では波面が詰まり、後ろでは間隔が広がることを確かめよう。音源が動いても音速 $V$ は変わらない（音速は空気に対する速さで、音源の速さによらない）。',
      ),
    ),
    section(
      '観測者が動くと、波面に出会う割合が変わる',
      p(
        '観測者に対する音の速さは $V - v_{\\mathrm{O}}$ になる。観測者は 1 秒間に $(V - v_{\\mathrm{O}})/\\lambda_1$ 枚の波面に出会うので、これが観測振動数になる。',
      ),
      eq(
        'f = \\frac{V - v_{\\mathrm{O}}}{\\lambda_1} = \\frac{V - v_{\\mathrm{O}}}{V - v_{\\mathrm{S}}}\\, f_0',
      ),
      p(
        'シミュレーションでは、波面が観測者に届いた時刻を記録し、その間隔の逆数を「観測振動数（測定）」として表示している。公式の値と一致することを確かめよう。',
      ),
    ),
    section(
      '風があるとき',
      p(
        '風速 $w$（音源 → 観測者の向きを正）の風が吹くと、地面に対する音の速さが $V + w$ になる。公式の $V$ を $V + w$ に置き換えればよい。',
      ),
      eq('f = \\frac{V + w - v_{\\mathrm{O}}}{V + w - v_{\\mathrm{S}}}\\, f_0'),
      p(
        '音源と観測者が静止していれば、風があっても振動数は変わらない（波長と音の速さが同じ割合で変わる）。',
      ),
    ),
    section(
      'グラフの読み方',
      ul(
        '「観測振動数」のグラフ: 最初の音が届くまでは何も聞こえない。音源が観測者とすれ違うと、振動数は高い値 $f_1$ から低い値 $f_2$ へ一気に下がる',
        '「届く音の波形」のグラフ: 観測者に届く空気の振動（実線）と音源の振動（破線）を比べると、近づくときは波が詰まって（振動数が高く）見える',
      ),
    ),
    note(
      '入試のポイント',
      ul(
        '公式の正の向きは「音源 → 観測者」。速度の符号を、この向きに合わせて決める',
        '音源が動くと波長が変わり、観測者が動くと（観測者に対する）音の速さが変わる。どちらの効果かを分けて考える',
        '風は音速 $V$ を $V \\pm w$ に置き換える。音源の前後で風の向きの符号が逆になることに注意',
        '壁で反射する問題は「壁が観測者として受け取り、同じ振動数で音源として出す」と 2 段階に分ける',
      ),
    ),
    section(
      '考えてみよう',
      question(
        '振動数 500 Hz の音源が 34 m/s で静止した観測者に近づく。観測者が聞く振動数は？（音速 340 m/s）',
        p(
          '$f = \\dfrac{340}{340 - 34}\\times 500 \\approx 556$ Hz。既定の条件の「すれ違う前」の値で確かめよう。すれ違った後は $\\dfrac{340}{340 + 34}\\times 500 \\approx 455$ Hz。',
        ),
      ),
      question(
        '音源を止め（$v_{\\mathrm{S}} = 0$）、観測者が 34 m/s で音源に近づくと、振動数は何 Hz になるか。音源が同じ速さで近づく場合と同じか。',
        p(
          '観測者の速度は音源に向かう向き（左向き）なので $v_{\\mathrm{O}} = -34$ m/s。$f = \\dfrac{340 + 34}{340}\\times 500 = 550$ Hz で、音源が近づく場合（556 Hz）とわずかに違う。相対速度だけでは決まらない。',
        ),
      ),
      question(
        '音源と観測者を静止させ、風速を 20 m/s にすると、波長と観測振動数はどうなるか。',
        p(
          '右向きに進む音の波長は $(340+20)/500 = 0.72$ m に伸びるが、観測者に対する音の速さも $360$ m/s になるので振動数は 500 Hz のまま。',
        ),
      ),
    ),
    section(
      '数値計算について',
      p(
        '音源は時刻 $k/f_0$（$k = 0, 1, 2, \\dots$）ごとに波面を出し、波面は放出位置を中心に半径 $V t$ で広がる（風があれば中心が流される）。音源・観測者・波面はどれも等速で動くので、波面が観測者に届く時刻は刻み幅によらず厳密に求められる。到達間隔から測った振動数・波面の間隔が公式と一致することは、パラメータ範囲の全隅で自動テストしている。音は速いので、画面は 1/50 倍のスロー再生にしている。',
      ),
    ),
  );
}
